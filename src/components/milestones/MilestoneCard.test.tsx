import { describe, it, expect, vi } from 'vitest';
import { render, screen, fireEvent } from '@testing-library/react';
import { MilestoneCard } from './MilestoneCard';
import type { Milestone } from '@/domain/types';

describe('MilestoneCard', () => {
  const mockAutoMilestone: Milestone = {
    id: -1,
    title: 'Centurion',
    description: 'Solved 100 practice questions',
    date: '2026-10-05',
    isAutoGenerated: true,
    category: 'question_count',
    createdAt: '',
  };

  const mockCustomMilestone: Milestone = {
    id: 12,
    title: 'Bought Guidebooks',
    description: 'Targeted DUET preparation books',
    date: '2026-10-02',
    isAutoGenerated: false,
    category: 'custom',
    createdAt: '',
  };

  it('renders auto-generated milestone details and achievement tag', () => {
    render(<MilestoneCard milestone={mockAutoMilestone} />);

    expect(screen.getByText('Centurion')).toBeInTheDocument();
    expect(
      screen.getByText('Solved 100 practice questions'),
    ).toBeInTheDocument();
    expect(screen.getByText('Unlocked Achievement')).toBeInTheDocument();
    expect(screen.getByText('Practice Questions')).toBeInTheDocument();
    expect(screen.getByText('2026-10-05')).toBeInTheDocument();
    // Auto milestones do not render delete button
    expect(screen.queryByText(/Delete/i)).not.toBeInTheDocument();
  });

  it('renders custom milestone with personal goal tag and delete button', () => {
    const onDelete = vi.fn();
    render(
      <MilestoneCard milestone={mockCustomMilestone} onDelete={onDelete} />,
    );

    expect(screen.getByText('Bought Guidebooks')).toBeInTheDocument();
    expect(screen.getByText('Personal Goal')).toBeInTheDocument();
    expect(screen.getByText('Custom Milestone')).toBeInTheDocument();

    const deleteBtn = screen.getByRole('button', { name: /Delete milestone/i });
    expect(deleteBtn).toBeInTheDocument();
  });

  it('shows confirmation and invokes onDelete when confirmed', () => {
    const onDelete = vi.fn();
    render(
      <MilestoneCard milestone={mockCustomMilestone} onDelete={onDelete} />,
    );

    // Click delete trigger
    fireEvent.click(screen.getByRole('button', { name: /Delete milestone/i }));
    expect(screen.getByText('Delete milestone?')).toBeInTheDocument();

    // Confirm deletion
    const confirmBtn = screen.getByRole('button', { name: /Yes, Delete/i });
    fireEvent.click(confirmBtn);

    expect(onDelete).toHaveBeenCalledWith(12);
  });
});
