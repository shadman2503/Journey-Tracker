import React, { useState } from 'react';
import {
  Trophy,
  Target,
  Flame,
  BookOpen,
  FileCheck,
  Clock,
  Flag,
  Sparkles,
  Calendar,
  Trash2,
  Award,
} from 'lucide-react';
import type { Milestone, MilestoneCategory } from '@/domain/types';
import { Button } from '@/components/ui/button';

interface MilestoneCardProps {
  milestone: Milestone;
  onDelete?: (id: number) => void;
}

const CATEGORY_META: Record<
  MilestoneCategory,
  { label: string; bg: string; text: string; icon: React.ElementType }
> = {
  syllabus: {
    label: 'Syllabus',
    bg: 'bg-emerald-500/10 border-emerald-500/20',
    text: 'text-emerald-500 dark:text-emerald-400',
    icon: BookOpen,
  },
  streak: {
    label: 'Streak',
    bg: 'bg-amber-500/10 border-amber-500/20',
    text: 'text-amber-500 dark:text-amber-400',
    icon: Flame,
  },
  mock: {
    label: 'Mock Test',
    bg: 'bg-sky-500/10 border-sky-500/20',
    text: 'text-sky-500 dark:text-sky-400',
    icon: FileCheck,
  },
  question_count: {
    label: 'Practice Questions',
    bg: 'bg-indigo-500/10 border-indigo-500/20',
    text: 'text-indigo-500 dark:text-indigo-400',
    icon: Target,
  },
  study_time: {
    label: 'Study Hours',
    bg: 'bg-violet-500/10 border-violet-500/20',
    text: 'text-violet-500 dark:text-violet-400',
    icon: Clock,
  },
  custom: {
    label: 'Custom Milestone',
    bg: 'bg-fuchsia-500/10 border-fuchsia-500/20',
    text: 'text-fuchsia-500 dark:text-fuchsia-400',
    icon: Flag,
  },
};

export const MilestoneCard: React.FC<MilestoneCardProps> = ({
  milestone,
  onDelete,
}) => {
  const [showConfirmDelete, setShowConfirmDelete] = useState(false);

  const categoryInfo =
    CATEGORY_META[milestone.category] || CATEGORY_META.custom;
  const CategoryIcon = categoryInfo.icon;

  const handleDelete = () => {
    if (milestone.id !== undefined && onDelete) {
      onDelete(milestone.id);
    }
  };

  return (
    <div className='relative flex flex-col justify-between p-4.5 rounded-xl border bg-card text-card-foreground shadow-xs transition-all hover:border-border/80 hover:shadow-md'>
      {/* Top badges bar */}
      <div className='flex items-center justify-between gap-2 mb-3'>
        <div className='flex items-center gap-2 flex-wrap'>
          {/* Category Chip */}
          <span
            className={`inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-semibold border ${categoryInfo.bg} ${categoryInfo.text}`}
          >
            <CategoryIcon className='h-3.5 w-3.5' />
            {categoryInfo.label}
          </span>

          {/* Source Tag */}
          {milestone.isAutoGenerated ? (
            <span className='inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-medium bg-teal-500/10 text-teal-600 dark:text-teal-400 border border-teal-500/20'>
              <Sparkles className='h-3 w-3' />
              Unlocked Achievement
            </span>
          ) : (
            <span className='inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-medium bg-muted text-muted-foreground border'>
              <Award className='h-3 w-3' />
              Personal Goal
            </span>
          )}
        </div>

        {/* Date */}
        <div className='flex items-center gap-1 text-xs text-muted-foreground whitespace-nowrap'>
          <Calendar className='h-3.5 w-3.5' />
          <span>{milestone.date}</span>
        </div>
      </div>

      {/* Main Content */}
      <div className='flex items-start gap-3 my-1'>
        <div
          className={`shrink-0 p-2.5 rounded-xl border ${categoryInfo.bg} ${categoryInfo.text}`}
        >
          {milestone.category === 'syllabus' ? (
            <Trophy className='h-5 w-5' />
          ) : (
            <CategoryIcon className='h-5 w-5' />
          )}
        </div>
        <div className='flex-1 min-w-0'>
          <h3 className='text-base font-semibold text-foreground tracking-tight line-clamp-1'>
            {milestone.title}
          </h3>
          <p className='text-xs text-muted-foreground mt-1 leading-relaxed'>
            {milestone.description}
          </p>
        </div>
      </div>

      {/* Actions (for custom milestones only) */}
      {!milestone.isAutoGenerated && milestone.id !== undefined && onDelete && (
        <div className='mt-3 pt-3 border-t flex items-center justify-end'>
          {showConfirmDelete ? (
            <div className='flex items-center gap-2 animate-in fade-in-0'>
              <span className='text-xs text-rose-500 font-medium'>
                Delete milestone?
              </span>
              <Button
                variant='destructive'
                size='sm'
                onClick={handleDelete}
                className='h-7 px-2.5 text-xs'
              >
                Yes, Delete
              </Button>
              <Button
                variant='ghost'
                size='sm'
                onClick={() => setShowConfirmDelete(false)}
                className='h-7 px-2 text-xs'
              >
                Cancel
              </Button>
            </div>
          ) : (
            <button
              type='button'
              onClick={() => setShowConfirmDelete(true)}
              aria-label='Delete milestone'
              className='text-xs text-muted-foreground hover:text-rose-500 transition-colors inline-flex items-center gap-1 p-1 rounded-md hover:bg-rose-500/10'
            >
              <Trash2 className='h-3.5 w-3.5' />
              <span>Delete</span>
            </button>
          )}
        </div>
      )}
    </div>
  );
};
