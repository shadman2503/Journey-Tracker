import { describe, it, expect, vi } from 'vitest';
import { render, screen, fireEvent } from '@testing-library/react';
import { MilestoneDashboardWidget } from './MilestoneDashboardWidget';
import type { Milestone } from '@/domain/types';

describe('MilestoneDashboardWidget', () => {
  const mockMilestones: Milestone[] = [
    {
      id: -1,
      title: 'Centurion',
      description: 'Solved 100 practice questions',
      date: '2026-10-05',
      isAutoGenerated: true,
      category: 'question_count',
      createdAt: '',
    },
    {
      id: -2,
      title: 'Weekly Warrior',
      description: '7-day study streak',
      date: '2026-10-04',
      isAutoGenerated: true,
      category: 'streak',
      createdAt: '',
    },
    {
      id: -3,
      title: 'Journey Begun',
      description: 'First prep activity recorded',
      date: '2026-10-01',
      isAutoGenerated: true,
      category: 'syllabus',
      createdAt: '',
    },
  ];

  it('renders empty state when there are no milestones', () => {
    const onAddGoal = vi.fn();
    render(<MilestoneDashboardWidget milestones={[]} onAddGoal={onAddGoal} />);

    expect(screen.getByText('No Milestones Unlocked Yet')).toBeInTheDocument();

    const addBtn = screen.getByRole('button', { name: /Add First Milestone/i });
    fireEvent.click(addBtn);
    expect(onAddGoal).toHaveBeenCalledTimes(1);
  });

  it('renders unlocked milestone count and latest achievement spotlight', () => {
    const onViewAll = vi.fn();
    render(
      <MilestoneDashboardWidget
        milestones={mockMilestones}
        onViewAll={onViewAll}
      />,
    );

    expect(screen.getByText('3 Unlocked')).toBeInTheDocument();
    expect(screen.getByText('Centurion')).toBeInTheDocument();
    expect(
      screen.getByText('Solved 100 practice questions'),
    ).toBeInTheDocument();
    expect(screen.getByText('Latest Achievement')).toBeInTheDocument();

    // Secondary items
    expect(screen.getByText('Weekly Warrior')).toBeInTheDocument();
    expect(screen.getByText('Journey Begun')).toBeInTheDocument();

    // View Journey button
    const viewBtn = screen.getByRole('button', { name: /View Journey/i });
    fireEvent.click(viewBtn);
    expect(onViewAll).toHaveBeenCalledTimes(1);
  });
});
