import { describe, it, expect, vi } from 'vitest';
import { render, screen, fireEvent } from '@testing-library/react';
import { MilestoneList } from './MilestoneList';
import type { Milestone } from '@/domain/types';

describe('MilestoneList', () => {
  const mockMilestones: Milestone[] = [
    {
      id: -1,
      title: 'Centurion',
      description: 'Solved 100 questions',
      date: '2026-10-05',
      isAutoGenerated: true,
      category: 'question_count',
      createdAt: '',
    },
    {
      id: -2,
      title: 'Weekly Warrior',
      description: '7-day streak',
      date: '2026-10-08',
      isAutoGenerated: true,
      category: 'streak',
      createdAt: '',
    },
    {
      id: 1,
      title: 'Bought Guidebooks',
      description: 'Previous year DUET questions',
      date: '2026-10-02',
      isAutoGenerated: false,
      category: 'custom',
      createdAt: '',
    },
  ];

  it('renders summary stat cards and list of milestone cards', () => {
    render(<MilestoneList milestones={mockMilestones} />);

    expect(screen.getByText('Total Milestones Recorded')).toBeInTheDocument();
    expect(screen.getByText('Auto-Unlocked Achievements')).toBeInTheDocument();
    expect(screen.getByText('Personal Goals Logged')).toBeInTheDocument();

    expect(screen.getByText('Centurion')).toBeInTheDocument();
    expect(screen.getByText('Weekly Warrior')).toBeInTheDocument();
    expect(screen.getByText('Bought Guidebooks')).toBeInTheDocument();
  });

  it('filters milestones by search text query', () => {
    render(<MilestoneList milestones={mockMilestones} />);

    const searchInput = screen.getByPlaceholderText(/Search milestones by title or description/i);
    fireEvent.change(searchInput, { target: { value: 'Warrior' } });

    expect(screen.getByText('Weekly Warrior')).toBeInTheDocument();
    expect(screen.queryByText('Centurion')).not.toBeInTheDocument();
    expect(screen.queryByText('Bought Guidebooks')).not.toBeInTheDocument();
  });

  it('filters milestones by source pills', () => {
    render(<MilestoneList milestones={mockMilestones} />);

    // Filter to Achievements only
    fireEvent.click(screen.getByRole('button', { name: /Achievements \(2\)/i }));

    expect(screen.getByText('Centurion')).toBeInTheDocument();
    expect(screen.getByText('Weekly Warrior')).toBeInTheDocument();
    expect(screen.queryByText('Bought Guidebooks')).not.toBeInTheDocument();

    // Filter to Personal Goals only
    fireEvent.click(screen.getByRole('button', { name: /Personal Goals \(1\)/i }));

    expect(screen.getByText('Bought Guidebooks')).toBeInTheDocument();
    expect(screen.queryByText('Centurion')).not.toBeInTheDocument();
  });

  it('filters milestones by category pills', () => {
    render(<MilestoneList milestones={mockMilestones} />);

    fireEvent.click(screen.getByRole('button', { name: /Streaks \(1\)/i }));

    expect(screen.getByText('Weekly Warrior')).toBeInTheDocument();
    expect(screen.queryByText('Centurion')).not.toBeInTheDocument();
    expect(screen.queryByText('Bought Guidebooks')).not.toBeInTheDocument();
  });

  it('toggles sort order', () => {
    render(<MilestoneList milestones={mockMilestones} />);

    const sortBtn = screen.getByRole('button', { name: /Newest First/i });
    expect(sortBtn).toBeInTheDocument();

    fireEvent.click(sortBtn);
    expect(screen.getByRole('button', { name: /Oldest First/i })).toBeInTheDocument();
  });

  it('renders empty state when no milestones match criteria and provides reset button', () => {
    render(<MilestoneList milestones={mockMilestones} />);

    const searchInput = screen.getByPlaceholderText(/Search milestones by title or description/i);
    fireEvent.change(searchInput, { target: { value: 'Nonexistent query' } });

    expect(screen.getByText('No Milestones Found')).toBeInTheDocument();
    const resetBtn = screen.getByRole('button', { name: /Reset Filters/i });
    expect(resetBtn).toBeInTheDocument();

    fireEvent.click(resetBtn);
    expect(screen.getByText('Centurion')).toBeInTheDocument();
  });

  it('invokes onOpenAddModal when clicking Add Goal button', () => {
    const onOpenAdd = vi.fn();
    render(<MilestoneList milestones={mockMilestones} onOpenAddModal={onOpenAdd} />);

    const addBtn = screen.getByRole('button', { name: /Add Goal/i });
    fireEvent.click(addBtn);

    expect(onOpenAdd).toHaveBeenCalledTimes(1);
  });
});

