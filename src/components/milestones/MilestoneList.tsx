import React, { useState, useMemo } from 'react';
import {
  Search,
  Plus,
  ArrowUpDown,
  Sparkles,
  Trophy,
  Award,
  X,
  Layers,
} from 'lucide-react';
import type { Milestone, MilestoneCategory } from '@/domain/types';
import {
  getMilestoneSummary,
  filterAndSortMilestones,
  ALL_MILESTONE_CATEGORIES,
} from '@/domain/milestones';
import { MilestoneCard } from './MilestoneCard';
import { Button } from '@/components/ui/button';

interface MilestoneListProps {
  milestones: Milestone[];
  onDeleteMilestone?: (id: number) => void;
  onOpenAddModal?: () => void;
}

const CATEGORY_LABELS: Record<MilestoneCategory, string> = {
  syllabus: 'Syllabus',
  streak: 'Streaks',
  mock: 'Mock Tests',
  question_count: 'Questions',
  study_time: 'Study Hours',
  custom: 'Custom',
};

export const MilestoneList: React.FC<MilestoneListProps> = ({
  milestones,
  onDeleteMilestone,
  onOpenAddModal,
}) => {
  const [searchQuery, setSearchQuery] = useState('');
  const [selectedCategory, setSelectedCategory] = useState<MilestoneCategory | 'all'>('all');
  const [selectedSource, setSelectedSource] = useState<'all' | 'auto' | 'custom'>('all');
  const [sortOrder, setSortOrder] = useState<'newest' | 'oldest'>('newest');

  const summary = useMemo(() => getMilestoneSummary(milestones), [milestones]);

  const filteredMilestones = useMemo(() => {
    return filterAndSortMilestones(milestones, {
      category: selectedCategory,
      source: selectedSource,
      searchQuery,
      sortOrder,
    });
  }, [milestones, selectedCategory, selectedSource, searchQuery, sortOrder]);

  const toggleSortOrder = () => {
    setSortOrder((prev) => (prev === 'newest' ? 'oldest' : 'newest'));
  };

  const handleResetFilters = () => {
    setSearchQuery('');
    setSelectedCategory('all');
    setSelectedSource('all');
    setSortOrder('newest');
  };

  const hasActiveFilters =
    searchQuery.trim().length > 0 ||
    selectedCategory !== 'all' ||
    selectedSource !== 'all';

  return (
    <div className="space-y-6">
      {/* Summary Metrics Bar */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
        {/* Total Milestones */}
        <div className="p-4 rounded-xl border bg-card text-card-foreground flex items-center gap-3.5 shadow-xs">
          <div className="p-2.5 rounded-xl bg-primary/10 text-primary">
            <Trophy className="h-5 w-5" />
          </div>
          <div>
            <div className="text-2xl font-bold tracking-tight text-foreground">
              {summary.totalMilestones}
            </div>
            <div className="text-xs text-muted-foreground font-medium">
              Total Milestones Recorded
            </div>
          </div>
        </div>

        {/* Unlocked Achievements */}
        <div className="p-4 rounded-xl border bg-card text-card-foreground flex items-center gap-3.5 shadow-xs">
          <div className="p-2.5 rounded-xl bg-teal-500/10 text-teal-600 dark:text-teal-400">
            <Sparkles className="h-5 w-5" />
          </div>
          <div>
            <div className="text-2xl font-bold tracking-tight text-foreground">
              {summary.autoGeneratedCount}
            </div>
            <div className="text-xs text-muted-foreground font-medium">
              Auto-Unlocked Achievements
            </div>
          </div>
        </div>

        {/* Personal Goals */}
        <div className="p-4 rounded-xl border bg-card text-card-foreground flex items-center gap-3.5 shadow-xs">
          <div className="p-2.5 rounded-xl bg-indigo-500/10 text-indigo-600 dark:text-indigo-400">
            <Award className="h-5 w-5" />
          </div>
          <div>
            <div className="text-2xl font-bold tracking-tight text-foreground">
              {summary.customCount}
            </div>
            <div className="text-xs text-muted-foreground font-medium">
              Personal Goals Logged
            </div>
          </div>
        </div>
      </div>

      {/* Control Filter Bar */}
      <div className="p-4 rounded-xl border bg-card text-card-foreground space-y-4 shadow-xs">
        {/* Top row: search + sort + add action */}
        <div className="flex flex-col sm:flex-row gap-3 items-stretch sm:items-center justify-between">
          {/* Search bar */}
          <div className="relative flex-1">
            <Search className="absolute left-3 top-1/2 -translate-y-1/2 h-4 w-4 text-muted-foreground" />
            <input
              type="text"
              placeholder="Search milestones by title or description..."
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              className="w-full pl-9 pr-8 py-2 text-sm rounded-lg border bg-background text-foreground focus:outline-hidden focus:ring-2 focus:ring-primary/50"
            />
            {searchQuery && (
              <button
                type="button"
                onClick={() => setSearchQuery('')}
                aria-label="Clear milestone search"
                className="absolute right-2.5 top-1/2 -translate-y-1/2 text-muted-foreground hover:text-foreground"
              >
                <X className="h-4 w-4" />
              </button>
            )}
          </div>

          <div className="flex items-center gap-2">
            {/* Sort Toggle */}
            <Button
              type="button"
              variant="outline"
              size="sm"
              onClick={toggleSortOrder}
              className="h-9 gap-1.5 text-xs shrink-0"
            >
              <ArrowUpDown className="h-3.5 w-3.5" />
              <span>{sortOrder === 'newest' ? 'Newest First' : 'Oldest First'}</span>
            </Button>

            {/* Add Custom Milestone */}
            {onOpenAddModal && (
              <Button
                type="button"
                size="sm"
                onClick={onOpenAddModal}
                className="h-9 gap-1.5 text-xs bg-primary text-primary-foreground hover:bg-primary/90 shrink-0"
              >
                <Plus className="h-4 w-4" />
                <span>Add Goal</span>
              </Button>
            )}
          </div>
        </div>

        {/* Filter row: Origin / Source segmented control */}
        <div className="flex items-center gap-2 border-t pt-3 flex-wrap">
          <span className="text-xs font-semibold text-muted-foreground mr-1">
            Source:
          </span>
          <button
            type="button"
            onClick={() => setSelectedSource('all')}
            className={`px-2.5 py-1 text-xs font-medium rounded-lg border transition-colors ${
              selectedSource === 'all'
                ? 'bg-primary text-primary-foreground border-primary'
                : 'bg-muted/50 text-muted-foreground hover:bg-muted border-transparent'
            }`}
          >
            All Sources ({milestones.length})
          </button>
          <button
            type="button"
            onClick={() => setSelectedSource('auto')}
            className={`px-2.5 py-1 text-xs font-medium rounded-lg border transition-colors ${
              selectedSource === 'auto'
                ? 'bg-teal-600 text-white border-teal-600'
                : 'bg-muted/50 text-muted-foreground hover:bg-muted border-transparent'
            }`}
          >
            Achievements ({summary.autoGeneratedCount})
          </button>
          <button
            type="button"
            onClick={() => setSelectedSource('custom')}
            className={`px-2.5 py-1 text-xs font-medium rounded-lg border transition-colors ${
              selectedSource === 'custom'
                ? 'bg-indigo-600 text-white border-indigo-600'
                : 'bg-muted/50 text-muted-foreground hover:bg-muted border-transparent'
            }`}
          >
            Personal Goals ({summary.customCount})
          </button>
        </div>

        {/* Filter row: Category pills */}
        <div className="flex items-center gap-1.5 overflow-x-auto pb-1 text-xs scrollbar-none">
          <span className="text-xs font-semibold text-muted-foreground mr-1 shrink-0">
            Category:
          </span>
          <button
            type="button"
            onClick={() => setSelectedCategory('all')}
            className={`px-2.5 py-1 rounded-full text-xs font-medium border transition-colors shrink-0 ${
              selectedCategory === 'all'
                ? 'bg-foreground text-background border-foreground font-semibold'
                : 'bg-muted/40 text-muted-foreground hover:bg-muted border-border/40'
            }`}
          >
            All Categories
          </button>
          {ALL_MILESTONE_CATEGORIES.map((cat) => {
            const count = summary.byCategory[cat] || 0;
            return (
              <button
                key={cat}
                type="button"
                onClick={() => setSelectedCategory(cat)}
                className={`px-2.5 py-1 rounded-full text-xs font-medium border transition-colors shrink-0 ${
                  selectedCategory === cat
                    ? 'bg-foreground text-background border-foreground font-semibold'
                    : 'bg-muted/40 text-muted-foreground hover:bg-muted border-border/40'
                }`}
              >
                {CATEGORY_LABELS[cat]} ({count})
              </button>
            );
          })}
        </div>
      </div>

      {/* Milestones Grid or Empty State */}
      {filteredMilestones.length === 0 ? (
        <div className="p-12 text-center rounded-2xl border border-dashed bg-card/50">
          <div className="mx-auto w-12 h-12 rounded-full bg-muted flex items-center justify-center text-muted-foreground mb-3">
            <Layers className="h-6 w-6" />
          </div>
          <h3 className="text-base font-semibold text-foreground mb-1">
            No Milestones Found
          </h3>
          <p className="text-xs text-muted-foreground max-w-sm mx-auto mb-4">
            {hasActiveFilters
              ? 'No milestones match your active filter or search criteria.'
              : 'Start logging study sessions, mock tests, and syllabus progress to automatically unlock achievements, or add personal goals.'}
          </p>
          <div className="flex items-center justify-center gap-2">
            {hasActiveFilters && (
              <Button
                variant="outline"
                size="sm"
                onClick={handleResetFilters}
                className="text-xs"
              >
                Reset Filters
              </Button>
            )}
            {onOpenAddModal && (
              <Button
                size="sm"
                onClick={onOpenAddModal}
                className="text-xs bg-primary text-primary-foreground hover:bg-primary/90"
              >
                <Plus className="h-3.5 w-3.5 mr-1" />
                Add Personal Goal
              </Button>
            )}
          </div>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
          {filteredMilestones.map((milestone) => (
            <MilestoneCard
              key={`${milestone.id}-${milestone.title}`}
              milestone={milestone}
              onDelete={onDeleteMilestone}
            />
          ))}
        </div>
      )}
    </div>
  );
};
