import { describe, it, expect, vi } from 'vitest';
import { render, screen, fireEvent } from '@testing-library/react';
import { JourneyTimeline } from './JourneyTimeline';
import type { Milestone } from '@/domain/types';

describe('JourneyTimeline', () => {
  const mockMilestones: Milestone[] = [
    {
      id: 1,
      title: 'Journey Begun',
      description: 'First preparation step logged',
      date: '2026-09-01',
      category: 'custom',
      isAutoGenerated: true,
      createdAt: '',
    },
    {
      id: 2,
      title: 'Centurion',
      description: 'Solved 100 practice questions',
      date: '2026-10-05',
      category: 'question_count',
      isAutoGenerated: true,
      createdAt: '',
    },
    {
      id: 3,
      title: 'Physics Marathon',
      description: 'Completed 5 topics in Physics',
      date: '2026-10-10',
      category: 'syllabus',
      isAutoGenerated: false,
      createdAt: '',
    },
  ];

  const targetExamDate = '2027-06-15';

  it('renders journey stats overview bar with days and progress bar', () => {
    render(
      <JourneyTimeline
        milestones={mockMilestones}
        targetExamDate={targetExamDate}
      />,
    );

    expect(screen.getByText('Preparation Journey Progress')).toBeInTheDocument();
    expect(screen.getByText('Milestones Recorded')).toBeInTheDocument();
    expect(screen.getByText('Days Elapsed')).toBeInTheDocument();
    expect(screen.getByText('Days to DUET Exam')).toBeInTheDocument();
    expect(screen.getByRole('progressbar')).toBeInTheDocument();
  });

  it('renders month section groups, milestone nodes, and target exam node', () => {
    render(
      <JourneyTimeline
        milestones={mockMilestones}
        targetExamDate={targetExamDate}
      />,
    );

    // Month headers
    expect(screen.getByText(/September 2026/i)).toBeInTheDocument();
    expect(screen.getByText(/October 2026/i)).toBeInTheDocument();
    expect(screen.getByText(/June 2027/i)).toBeInTheDocument();

    // Nodes
    expect(screen.getByText('Journey Begun')).toBeInTheDocument();
    expect(screen.getByText('Centurion')).toBeInTheDocument();
    expect(screen.getByText('Physics Marathon')).toBeInTheDocument();
    expect(screen.getByText('DUET Admission Test')).toBeInTheDocument();
    expect(screen.getByText('Ultimate Destination')).toBeInTheDocument();
  });

  it('filters timeline items by search query', () => {
    render(
      <JourneyTimeline
        milestones={mockMilestones}
        targetExamDate={targetExamDate}
      />,
    );

    const searchInput = screen.getByPlaceholderText('Search timeline events...');
    fireEvent.change(searchInput, { target: { value: 'Centurion' } });

    expect(screen.getByText('Centurion')).toBeInTheDocument();
    expect(screen.queryByText('Physics Marathon')).not.toBeInTheDocument();
  });

  it('filters timeline items by category pill', () => {
    render(
      <JourneyTimeline
        milestones={mockMilestones}
        targetExamDate={targetExamDate}
      />,
    );

    const syllabusFilter = screen.getByRole('button', { name: /^Syllabus$/i });
    fireEvent.click(syllabusFilter);

    expect(screen.getByText('Physics Marathon')).toBeInTheDocument();
    expect(screen.queryByText('Centurion')).not.toBeInTheDocument();
  });

  it('toggles sort order between chronological and latest first', () => {
    render(
      <JourneyTimeline
        milestones={mockMilestones}
        targetExamDate={targetExamDate}
      />,
    );

    const sortButton = screen.getByRole('button', {
      name: /Chronological/i,
    });
    expect(sortButton).toBeInTheDocument();

    fireEvent.click(sortButton);
    expect(screen.getByText('Latest First')).toBeInTheDocument();
  });

  it('renders empty state when search matches nothing', () => {
    render(
      <JourneyTimeline
        milestones={mockMilestones}
        targetExamDate={targetExamDate}
      />,
    );

    const searchInput = screen.getByPlaceholderText('Search timeline events...');
    fireEvent.change(searchInput, { target: { value: 'Non-existent item 12345' } });

    expect(screen.getByText('No Events on Timeline')).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Reset Filters' })).toBeInTheDocument();

    fireEvent.click(screen.getByRole('button', { name: 'Reset Filters' }));
    expect(screen.getByText('Centurion')).toBeInTheDocument();
  });

  it('calls onOpenAddModal when clicking Add Goal button', () => {
    const onOpenAdd = vi.fn();
    render(
      <JourneyTimeline
        milestones={mockMilestones}
        targetExamDate={targetExamDate}
        onOpenAddModal={onOpenAdd}
      />,
    );

    const addGoalBtn = screen.getByRole('button', { name: /Add Goal/i });
    fireEvent.click(addGoalBtn);

    expect(onOpenAdd).toHaveBeenCalledTimes(1);
  });
});

