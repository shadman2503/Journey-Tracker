import { describe, it, expect } from 'vitest';
import { render, screen } from '@testing-library/react';
import { TimelineDestinationNode } from './TimelineDestinationNode';
import type { TimelineItem } from '@/domain/timeline';

describe('TimelineDestinationNode', () => {
  const destinationItem: TimelineItem = {
    id: 'duet-admission-test-2027',
    type: 'exam_destination',
    title: 'DUET 2027 Admission Test',
    description: 'The target destination of your preparation journey.',
    date: '2027-06-15',
    category: 'destination',
    isAutoGenerated: true,
    isCompleted: false,
  };

  it('renders destination title, target date, and destination badges', () => {
    render(
      <TimelineDestinationNode item={destinationItem} daysRemaining={245} />,
    );

    expect(screen.getByText('DUET 2027 Admission Test')).toBeInTheDocument();
    expect(
      screen.getByText('The target destination of your preparation journey.'),
    ).toBeInTheDocument();
    expect(screen.getByText('Ultimate Destination')).toBeInTheDocument();
    expect(screen.getByText('Target: 2027-06-15')).toBeInTheDocument();
    expect(screen.getByText('245 Days Remaining')).toBeInTheDocument();
    expect(screen.getByText('DUET 2027')).toBeInTheDocument();
  });

  it('hides days remaining badge if daysRemaining is 0 or undefined', () => {
    render(<TimelineDestinationNode item={destinationItem} />);

    expect(screen.getByText('DUET 2027 Admission Test')).toBeInTheDocument();
    expect(screen.queryByText(/Days Remaining/i)).not.toBeInTheDocument();
  });
});

