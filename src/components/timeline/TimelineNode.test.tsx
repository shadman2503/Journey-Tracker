import { describe, it, expect } from 'vitest';
import { render, screen } from '@testing-library/react';
import { TimelineNode } from './TimelineNode';
import type { TimelineItem } from '@/domain/timeline';

describe('TimelineNode', () => {
  const mockItem: TimelineItem = {
    id: 'm-1',
    type: 'milestone',
    title: 'First Study Milestone',
    description: 'Completed 10 topics in Physics',
    date: '2026-10-05',
    category: 'syllabus',
    isAutoGenerated: true,
    isCompleted: true,
  };

  const mockCustomItem: TimelineItem = {
    id: 15,
    type: 'milestone',
    title: 'Registered Coaching',
    description: 'Enrolled in offline test series',
    date: '2026-10-08',
    category: 'custom',
    isAutoGenerated: false,
    isCompleted: true,
  };

  it('renders title, description, date, and category badge', () => {
    render(<TimelineNode item={mockItem} />);

    expect(screen.getByText('First Study Milestone')).toBeInTheDocument();
    expect(
      screen.getByText('Completed 10 topics in Physics'),
    ).toBeInTheDocument();
    expect(screen.getByText('2026-10-05')).toBeInTheDocument();
    expect(screen.getByText('Syllabus')).toBeInTheDocument();
    expect(screen.getByText('Achievement')).toBeInTheDocument();
  });

  it('renders custom goal badge when isAutoGenerated is false', () => {
    render(<TimelineNode item={mockCustomItem} />);

    expect(screen.getByText('Registered Coaching')).toBeInTheDocument();
    expect(
      screen.getByText('Enrolled in offline test series'),
    ).toBeInTheDocument();
    expect(screen.getByText('Goal')).toBeInTheDocument();
    expect(screen.getByText('Personal Goal')).toBeInTheDocument();
  });

  it('renders journey start node correctly', () => {
    const journeyStartItem: TimelineItem = {
      id: 'journey-start',
      type: 'journey_start',
      title: 'Journey Began',
      description: 'First preparation step logged',
      date: '2026-09-01',
      category: 'custom',
      isAutoGenerated: true,
      isCompleted: true,
    };

    const { container } = render(<TimelineNode item={journeyStartItem} />);

    expect(screen.getByText('Journey Began')).toBeInTheDocument();
    expect(
      screen.getByText('First preparation step logged'),
    ).toBeInTheDocument();
    expect(container.querySelector('.border-primary\\/40')).toBeInTheDocument();
  });
});

