import React from 'react';
import {
  Trophy,
  Target,
  Flame,
  BookOpen,
  FileCheck,
  Clock,
  Flag,
  Sparkles,
  Calendar,
  Compass,
  Award,
} from 'lucide-react';
import type { TimelineItem } from '@/domain/timeline';
import type { MilestoneCategory } from '@/domain/types';

interface TimelineNodeProps {
  item: TimelineItem;
  isLast?: boolean;
}

const CATEGORY_COLORS: Record<
  MilestoneCategory | 'destination',
  {
    bg: string;
    border: string;
    text: string;
    nodeBg: string;
    label: string;
    icon: React.ElementType;
  }
> = {
  syllabus: {
    bg: 'bg-emerald-500/10',
    border: 'border-emerald-500/30',
    text: 'text-emerald-500 dark:text-emerald-400',
    nodeBg: 'bg-emerald-500',
    label: 'Syllabus',
    icon: BookOpen,
  },
  streak: {
    bg: 'bg-amber-500/10',
    border: 'border-amber-500/30',
    text: 'text-amber-500 dark:text-amber-400',
    nodeBg: 'bg-amber-500',
    label: 'Streak',
    icon: Flame,
  },
  mock: {
    bg: 'bg-sky-500/10',
    border: 'border-sky-500/30',
    text: 'text-sky-500 dark:text-sky-400',
    nodeBg: 'bg-sky-500',
    label: 'Mock Test',
    icon: FileCheck,
  },
  question_count: {
    bg: 'bg-indigo-500/10',
    border: 'border-indigo-500/30',
    text: 'text-indigo-500 dark:text-indigo-400',
    nodeBg: 'bg-indigo-500',
    label: 'Questions',
    icon: Target,
  },
  study_time: {
    bg: 'bg-violet-500/10',
    border: 'border-violet-500/30',
    text: 'text-violet-500 dark:text-violet-400',
    nodeBg: 'bg-violet-500',
    label: 'Study Hours',
    icon: Clock,
  },
  custom: {
    bg: 'bg-fuchsia-500/10',
    border: 'border-fuchsia-500/30',
    text: 'text-fuchsia-500 dark:text-fuchsia-400',
    nodeBg: 'bg-fuchsia-500',
    label: 'Personal Goal',
    icon: Flag,
  },
  destination: {
    bg: 'bg-amber-500/10',
    border: 'border-amber-500/30',
    text: 'text-amber-500 dark:text-amber-400',
    nodeBg: 'bg-amber-500',
    label: 'Target Exam',
    icon: Trophy,
  },
};

export const TimelineNode: React.FC<TimelineNodeProps> = ({
  item,
  isLast = false,
}) => {
  const meta =
    CATEGORY_COLORS[item.category as MilestoneCategory | 'destination'] ||
    CATEGORY_COLORS.custom;

  const IconComponent =
    item.type === 'journey_start'
      ? Compass
      : item.category === 'syllabus'
      ? Trophy
      : meta.icon;

  return (
    <div className="relative flex items-start gap-4 sm:gap-6 group">
      {/* Spine line & Central Circle Pin */}
      <div className="relative flex flex-col items-center self-stretch shrink-0">
        {/* Connecting Line segment */}
        {!isLast && (
          <div className="absolute top-8 bottom-0 w-0.5 bg-border group-hover:bg-primary/40 transition-colors" />
        )}

        {/* Node Circle Pin */}
        <div
          className={`relative z-10 flex items-center justify-center w-8 h-8 rounded-full border-2 bg-background transition-transform duration-300 group-hover:scale-110 shadow-xs ${meta.border}`}
        >
          <span className={`w-2.5 h-2.5 rounded-full ${meta.nodeBg}`} />
        </div>
      </div>

      {/* Content Card */}
      <div
        className={`flex-1 mb-6 p-4 rounded-xl border bg-card text-card-foreground shadow-xs transition-all hover:border-border/80 hover:shadow-md ${
          item.type === 'journey_start' ? 'border-primary/40 bg-primary/5' : ''
        }`}
      >
        {/* Header row: Category + Date */}
        <div className="flex items-center justify-between gap-2 mb-2">
          <div className="flex items-center gap-2 flex-wrap">
            <span
              className={`inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs font-semibold border ${meta.bg} ${meta.text} ${meta.border}`}
            >
              <IconComponent className="h-3 w-3" />
              {meta.label}
            </span>

            {item.isAutoGenerated ? (
              <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-medium bg-teal-500/10 text-teal-600 dark:text-teal-400 border border-teal-500/20">
                <Sparkles className="h-3 w-3" />
                Achievement
              </span>
            ) : (
              <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-medium bg-muted text-muted-foreground border">
                <Award className="h-3 w-3" />
                Goal
              </span>
            )}
          </div>

          <div className="flex items-center gap-1 text-xs text-muted-foreground whitespace-nowrap">
            <Calendar className="h-3.5 w-3.5" />
            <span>{item.date}</span>
          </div>
        </div>

        {/* Title and Description */}
        <div className="mt-1">
          <h4 className="text-sm font-semibold text-foreground tracking-tight">
            {item.title}
          </h4>
          <p className="text-xs text-muted-foreground mt-1 leading-relaxed">
            {item.description}
          </p>
        </div>
      </div>
    </div>
  );
};

