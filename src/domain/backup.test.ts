import { describe, it, expect } from 'vitest';
import {
  validateBackupPayload,
  generateBackupPreview,
  generateBackupFilename,
  BACKUP_APP_NAME,
  CURRENT_BACKUP_VERSION,
  type BackupPayload,
  type EntityCounts,
} from './backup';

describe('backup domain validation and preview', () => {
  const validPayload: BackupPayload = {
    version: CURRENT_BACKUP_VERSION,
    appName: BACKUP_APP_NAME,
    exportedAt: '2026-10-12T10:00:00.000Z',
    data: {
      topicProgress: [
        {
          topicId: 'math-calc-01',
          status: 'strong',
          notes: 'Covered calculus formulas',
          updatedAt: '2026-10-10T12:00:00Z',
        },
      ],
      studySessions: [
        {
          id: 1,
          date: '2026-10-05',
          subjectId: 'math',
          topicId: 'math-calc-01',
          durationMinutes: 60,
          questionsSolved: 30,
          correctAnswers: 25,
          createdAt: '2026-10-05T14:00:00Z',
        },
      ],
      mistakes: [
        {
          id: 1,
          subjectId: 'math',
          topicId: 'math-calc-01',
          questionRef: 'Q12',
          whatWentWrong: 'Sign error in integral',
          correctSolution: 'Review signs',
          type: 'calculation',
          status: 'fixed',
          createdAt: '2026-10-05T14:30:00Z',
        },
      ],
      mockTests: [
        {
          id: 1,
          testName: 'DUET Model Test 1',
          date: '2026-10-08',
          subjectId: undefined,
          totalQuestions: 100,
          correctAnswers: 70,
          wrongAnswers: 20,
          score: 65,
          accuracy: 70,
          timeTakenMinutes: 120,
          createdAt: '2026-10-08T16:00:00Z',
        },
      ],
      milestones: [
        {
          id: 1,
          title: 'First 50 Questions Solved',
          description: 'Reached question milestone',
          date: '2026-10-05',
          isAutoGenerated: true,
          category: 'question_count',
          createdAt: '2026-10-05T15:00:00Z',
        },
      ],
      countdown: {
        targetDate: '2027-06-20T09:00:00+06:00',
        examTitle: 'DUET 2027 Admission Test',
      },
    },
    summary: {
      totalTopicsTracked: 1,
      totalSessions: 1,
      totalMistakes: 1,
      totalMockTests: 1,
      totalMilestones: 1,
    },
  };

  describe('validateBackupPayload', () => {
    it('successfully validates a valid backup object', () => {
      const result = validateBackupPayload(validPayload);
      expect(result.success).toBe(true);
      if (result.success) {
        expect(result.payload.version).toBe(1);
        expect(result.payload.data.studySessions.length).toBe(1);
      }
    });

    it('successfully validates a valid JSON string', () => {
      const jsonStr = JSON.stringify(validPayload);
      const result = validateBackupPayload(jsonStr);
      expect(result.success).toBe(true);
    });

    it('rejects invalid JSON syntax with descriptive error', () => {
      const corruptJson = '{ version: 1, appName: ';
      const result = validateBackupPayload(corruptJson);
      expect(result.success).toBe(false);
      if (!result.success) {
        expect(result.errors[0]).toMatch(/JSON Parse Error/i);
      }
    });

    it('rejects payload missing required top-level fields', () => {
      const incomplete = { version: 1 };
      const result = validateBackupPayload(incomplete);
      expect(result.success).toBe(false);
      if (!result.success) {
        expect(result.errors.some((e) => e.includes('appName'))).toBe(true);
        expect(result.errors.some((e) => e.includes('exportedAt'))).toBe(true);
      }
    });

    it('rejects payload with invalid entity status or enum values', () => {
      const invalidEnum = {
        ...validPayload,
        data: {
          ...validPayload.data,
          topicProgress: [
            {
              topicId: 'math-calc-01',
              status: 'unknown_status', // invalid enum
              updatedAt: '2026-10-10T12:00:00Z',
            },
          ],
        },
      };
      const result = validateBackupPayload(invalidEnum);
      expect(result.success).toBe(false);
      if (!result.success) {
        expect(result.errors.some((e) => e.includes('topicProgress'))).toBe(true);
      }
    });

    it('rejects negative questions or duration in sessions', () => {
      const invalidSession = {
        ...validPayload,
        data: {
          ...validPayload.data,
          studySessions: [
            {
              id: 1,
              date: '2026-10-05',
              subjectId: 'math',
              topicId: 'math-01',
              durationMinutes: -10, // invalid negative
              questionsSolved: 10,
              correctAnswers: 5,
              createdAt: '2026-10-05',
            },
          ],
        },
      };
      const result = validateBackupPayload(invalidSession);
      expect(result.success).toBe(false);
    });
  });

  describe('generateBackupPreview', () => {
    it('accurately computes incoming counts and preserves current counts', () => {
      const currentCounts: EntityCounts = {
        topicProgress: 5,
        studySessions: 12,
        mistakes: 3,
        mockTests: 2,
        milestones: 4,
      };

      const preview = generateBackupPreview(validPayload, currentCounts);
      expect(preview.version).toBe(1);
      expect(preview.exportedAt).toBe('2026-10-12T10:00:00.000Z');
      expect(preview.hasCountdown).toBe(true);
      expect(preview.incomingCounts.topicProgress).toBe(1);
      expect(preview.incomingCounts.studySessions).toBe(1);
      expect(preview.incomingCounts.mistakes).toBe(1);
      expect(preview.incomingCounts.mockTests).toBe(1);
      expect(preview.incomingCounts.milestones).toBe(1);
      expect(preview.currentCounts).toEqual(currentCounts);
    });
  });

  describe('generateBackupFilename', () => {
    it('formats dated filename properly', () => {
      const testDate = new Date(2026, 9, 12); // Oct 12, 2026
      expect(generateBackupFilename(testDate)).toBe(
        'duet-2027-journey-tracker-backup-2026-10-12.json',
      );
    });
  });
});
