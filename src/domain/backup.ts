import { z } from 'zod';

export const BACKUP_APP_NAME = 'DUET 2027 Journey Tracker';
export const CURRENT_BACKUP_VERSION = 1;

export const topicProgressSchema = z.object({
  topicId: z.string().min(1, 'Topic ID is required'),
  status: z.enum(['not_started', 'learning', 'practicing', 'strong', 'needs_revision']),
  notes: z.string().optional(),
  lastStudiedAt: z.string().optional(),
  updatedAt: z.string(),
});

export const studySessionSchema = z.object({
  id: z.number().optional(),
  date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Invalid date format (YYYY-MM-DD)'),
  subjectId: z.enum(['math', 'physics', 'chemistry', 'english', 'cse']),
  topicId: z.string().min(1, 'Topic ID is required'),
  durationMinutes: z.number().min(0, 'Duration must be positive'),
  questionsSolved: z.number().min(0, 'Questions solved must be non-negative'),
  correctAnswers: z.number().min(0, 'Correct answers must be non-negative'),
  notes: z.string().optional(),
  createdAt: z.string(),
});

export const mistakeSchema = z.object({
  id: z.number().optional(),
  subjectId: z.enum(['math', 'physics', 'chemistry', 'english', 'cse']),
  topicId: z.string().min(1, 'Topic ID is required'),
  questionRef: z.string().default(''),
  whatWentWrong: z.string().default(''),
  correctSolution: z.string().default(''),
  type: z.enum([
    'conceptual',
    'calculation',
    'formula',
    'careless',
    'misreading',
    'time_management',
  ]),
  status: z.enum(['unresolved', 'reviewing', 'fixed']),
  reviewDate: z.string().optional(),
  createdAt: z.string(),
});

export const mockTestSchema = z.object({
  id: z.number().optional(),
  testName: z.string().min(1, 'Test name is required'),
  date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Invalid date format (YYYY-MM-DD)'),
  subjectId: z.enum(['math', 'physics', 'chemistry', 'english', 'cse']).optional(),
  totalQuestions: z.number().min(1, 'Total questions must be at least 1'),
  correctAnswers: z.number().min(0, 'Correct answers must be non-negative'),
  wrongAnswers: z.number().min(0, 'Wrong answers must be non-negative'),
  score: z.number(),
  accuracy: z.number().min(0).max(100),
  timeTakenMinutes: z.number().min(0),
  notes: z.string().optional(),
  createdAt: z.string(),
});

export const milestoneSchema = z.object({
  id: z.number().optional(),
  title: z.string().min(1, 'Title is required'),
  description: z.string().default(''),
  date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Invalid date format (YYYY-MM-DD)'),
  isAutoGenerated: z.boolean().default(false),
  category: z.enum([
    'syllabus',
    'streak',
    'mock',
    'question_count',
    'study_time',
    'custom',
  ]),
  createdAt: z.string(),
  icon: z.string().optional(),
});

export const countdownBackupSchema = z
  .object({
    targetDate: z.string(),
    examTitle: z.string(),
  })
  .optional();

export const backupSummarySchema = z
  .object({
    totalTopicsTracked: z.number().default(0),
    totalSessions: z.number().default(0),
    totalMistakes: z.number().default(0),
    totalMockTests: z.number().default(0),
    totalMilestones: z.number().default(0),
  })
  .optional();

export const backupPayloadSchema = z.object({
  version: z.number().int().positive(),
  appName: z.string().min(1),
  exportedAt: z.string(),
  data: z.object({
    topicProgress: z.array(topicProgressSchema).default([]),
    studySessions: z.array(studySessionSchema).default([]),
    mistakes: z.array(mistakeSchema).default([]),
    mockTests: z.array(mockTestSchema).default([]),
    milestones: z.array(milestoneSchema).default([]),
    countdown: countdownBackupSchema,
  }),
  summary: backupSummarySchema,
});

export type BackupPayload = z.infer<typeof backupPayloadSchema>;
export type ImportMode = 'overwrite' | 'merge';

export interface ValidationSuccess {
  success: true;
  payload: BackupPayload;
}

export interface ValidationFailure {
  success: false;
  errors: string[];
}

export type ValidationResult = ValidationSuccess | ValidationFailure;

export interface EntityCounts {
  topicProgress: number;
  studySessions: number;
  mistakes: number;
  mockTests: number;
  milestones: number;
}

export interface ImportPreview {
  version: number;
  exportedAt: string;
  incomingCounts: EntityCounts;
  currentCounts: EntityCounts;
  hasCountdown: boolean;
}

/**
 * Validates raw JSON string or object against the backup payload schema.
 */
export function validateBackupPayload(rawJson: string | object): ValidationResult {
  try {
    const parsed = typeof rawJson === 'string' ? JSON.parse(rawJson) : rawJson;
    const result = backupPayloadSchema.safeParse(parsed);
    if (result.success) {
      return { success: true, payload: result.data };
    }
    const errors = result.error.errors.map((e) => {
      const path = e.path.join('.');
      return `${path ? path + ': ' : ''}${e.message}`;
    });
    return { success: false, errors };
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Invalid JSON format';
    return { success: false, errors: [`JSON Parse Error: ${message}`] };
  }
}

/**
 * Generates pre-import breakdown counts comparing incoming backup data against current records.
 */
export function generateBackupPreview(
  payload: BackupPayload,
  currentCounts: EntityCounts,
): ImportPreview {
  const incomingCounts: EntityCounts = {
    topicProgress: payload.data.topicProgress?.length || 0,
    studySessions: payload.data.studySessions?.length || 0,
    mistakes: payload.data.mistakes?.length || 0,
    mockTests: payload.data.mockTests?.length || 0,
    milestones: payload.data.milestones?.length || 0,
  };

  return {
    version: payload.version,
    exportedAt: payload.exportedAt,
    incomingCounts,
    currentCounts,
    hasCountdown: Boolean(payload.data.countdown),
  };
}

/**
 * Generates the default backup filename based on current date.
 */
export function generateBackupFilename(date: Date = new Date()): string {
  const yyyy = date.getFullYear();
  const mm = String(date.getMonth() + 1).padStart(2, '0');
  const dd = String(date.getDate()).padStart(2, '0');
  return `duet-2027-journey-tracker-backup-${yyyy}-${mm}-${dd}.json`;
}
