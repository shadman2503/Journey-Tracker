import { describe, it, expect } from 'vitest';
import {
  detectAutoMilestones,
  getMilestoneSummary,
  filterAndSortMilestones,
  createCustomMilestoneSchema,
} from './milestones';
import type {
  Milestone,
  StudySession,
  MockTest,
  TopicProgress,
  SyllabusTopic,
} from './types';

describe('milestones domain logic', () => {
  const sampleTopics: SyllabusTopic[] = [
    {
      id: 'math-01',
      name: 'Complex Numbers',
      subjectId: 'math',
      section: 'Algebra',
      chapter: 'Algebra',
      order: 1,
    },
    {
      id: 'math-02',
      name: 'Quadratic Equations',
      subjectId: 'math',
      section: 'Algebra',
      chapter: 'Algebra',
      order: 2,
    },
    {
      id: 'phy-01',
      name: 'Newtonian Mechanics',
      subjectId: 'physics',
      section: 'Mechanics',
      chapter: 'Mechanics',
      order: 3,
    },
    {
      id: 'phy-02',
      name: 'Work, Power & Energy',
      subjectId: 'physics',
      section: 'Mechanics',
      chapter: 'Mechanics',
      order: 4,
    },
  ];

  describe('detectAutoMilestones', () => {
    it('returns empty array when there are no sessions, mocks, or progress', () => {
      const result = detectAutoMilestones([], {}, [], []);
      expect(result).toEqual([]);
    });

    it('detects Journey Begun milestone on earliest session or mock test', () => {
      const sessions: StudySession[] = [
        {
          id: 1,
          date: '2026-10-05',
          subjectId: 'math',
          topicId: 'math-01',
          durationMinutes: 45,
          questionsSolved: 15,
          correctAnswers: 12,
          notes: '',
          createdAt: '2026-10-05T10:00:00.000Z',
        },
      ];
      const result = detectAutoMilestones(sampleTopics, {}, sessions, []);
      const journeyStart = result.find((m) => m.title === 'Journey Begun');
      expect(journeyStart).toBeDefined();
      expect(journeyStart?.date).toBe('2026-10-05');
      expect(journeyStart?.isAutoGenerated).toBe(true);
      expect(journeyStart?.id).toBeLessThan(0);
    });

    it('detects Question Count milestones with exact session dates', () => {
      const sessions: StudySession[] = [
        {
          id: 1,
          date: '2026-10-01',
          subjectId: 'math',
          topicId: 'math-01',
          durationMinutes: 30,
          questionsSolved: 30,
          correctAnswers: 25,
          createdAt: '2026-10-01T10:00:00.000Z',
        },
        {
          id: 2,
          date: '2026-10-02',
          subjectId: 'math',
          topicId: 'math-01',
          durationMinutes: 30,
          questionsSolved: 30, // Total: 60 (crosses 50)
          correctAnswers: 25,
          createdAt: '2026-10-02T10:00:00.000Z',
        },
        {
          id: 3,
          date: '2026-10-04',
          subjectId: 'math',
          topicId: 'math-02',
          durationMinutes: 45,
          questionsSolved: 50, // Total: 110 (crosses 100)
          correctAnswers: 45,
          createdAt: '2026-10-04T10:00:00.000Z',
        },
      ];

      const result = detectAutoMilestones(sampleTopics, {}, sessions, []);
      const fiftyQ = result.find((m) => m.title === 'Fifty Questions Down');
      expect(fiftyQ).toBeDefined();
      expect(fiftyQ?.date).toBe('2026-10-02');
      expect(fiftyQ?.category).toBe('question_count');

      const hundredQ = result.find((m) => m.title === 'Centurion');
      expect(hundredQ).toBeDefined();
      expect(hundredQ?.date).toBe('2026-10-04');
    });

    it('detects Study Hours milestones with session dates', () => {
      const sessions: StudySession[] = [
        {
          id: 1,
          date: '2026-10-01',
          subjectId: 'physics',
          topicId: 'phy-01',
          durationMinutes: 400,
          questionsSolved: 20,
          correctAnswers: 18,
          createdAt: '2026-10-01T10:00:00.000Z',
        },
        {
          id: 2,
          date: '2026-10-03',
          subjectId: 'physics',
          topicId: 'phy-02',
          durationMinutes: 300, // Total 700m (crosses 600m / 10h)
          questionsSolved: 20,
          correctAnswers: 18,
          createdAt: '2026-10-03T10:00:00.000Z',
        },
      ];

      const result = detectAutoMilestones(sampleTopics, {}, sessions, []);
      const tenHours = result.find((m) => m.title === '10 Hours Dedicated');
      expect(tenHours).toBeDefined();
      expect(tenHours?.date).toBe('2026-10-03');
      expect(tenHours?.category).toBe('study_time');
    });

    it('detects Consecutive Streak milestones', () => {
      const sessions: StudySession[] = [
        {
          id: 1,
          date: '2026-10-01',
          subjectId: 'math',
          topicId: 'math-01',
          durationMinutes: 30,
          questionsSolved: 10,
          correctAnswers: 8,
          createdAt: '2026-10-01T00:00:00.000Z',
        },
        {
          id: 2,
          date: '2026-10-02',
          subjectId: 'math',
          topicId: 'math-01',
          durationMinutes: 30,
          questionsSolved: 10,
          correctAnswers: 8,
          createdAt: '2026-10-02T00:00:00.000Z',
        },
        {
          id: 3,
          date: '2026-10-03',
          subjectId: 'math',
          topicId: 'math-01',
          durationMinutes: 30,
          questionsSolved: 10,
          correctAnswers: 8,
          createdAt: '2026-10-03T00:00:00.000Z',
        },
      ];

      const result = detectAutoMilestones(sampleTopics, {}, sessions, []);
      const streak3 = result.find((m) => m.title === 'Consistency Spark');
      expect(streak3).toBeDefined();
      expect(streak3?.date).toBe('2026-10-03');
      expect(streak3?.category).toBe('streak');
    });

    it('detects Syllabus Mastery milestones including First Topic and Subject Completion', () => {
      const progressMap: Record<string, TopicProgress> = {
        'math-01': {
          topicId: 'math-01',
          status: 'strong',
          updatedAt: '2026-10-02T10:00:00.000Z',
        },
        'math-02': {
          topicId: 'math-02',
          status: 'strong',
          updatedAt: '2026-10-05T10:00:00.000Z',
        },
      };

      const result = detectAutoMilestones(sampleTopics, progressMap, [], []);
      const firstTopic = result.find((m) => m.title === 'First Topic Mastered');
      expect(firstTopic).toBeDefined();
      expect(firstTopic?.date).toBe('2026-10-02');

      const mathMastered = result.find((m) => m.title === 'Mathematics Mastered');
      expect(mathMastered).toBeDefined();
      expect(mathMastered?.date).toBe('2026-10-05');

      const halfway = result.find((m) => m.title === 'Halfway Milestone');
      expect(halfway).toBeDefined(); // 2 out of 4 topics strong = 50%
    });

    it('detects Mock Test milestones', () => {
      const mockTests: MockTest[] = [
        {
          id: 1,
          testName: 'Model Test 1',
          date: '2026-10-08',
          subjectId: 'math',
          totalQuestions: 50,
          correctAnswers: 38,
          wrongAnswers: 12,
          score: 140,
          accuracy: 76,
          timeTakenMinutes: 60,
          createdAt: '2026-10-08T12:00:00.000Z',
        },
        {
          id: 2,
          testName: 'Model Test 2',
          date: '2026-10-12',
          subjectId: undefined,
          totalQuestions: 100,
          correctAnswers: 85,
          wrongAnswers: 15,
          score: 325,
          accuracy: 85,
          timeTakenMinutes: 120,
          createdAt: '2026-10-12T12:00:00.000Z',
        },
      ];

      const result = detectAutoMilestones(sampleTopics, {}, [], mockTests);
      const firstMock = result.find((m) => m.title === 'First Mock Trial');
      expect(firstMock).toBeDefined();
      expect(firstMock?.date).toBe('2026-10-08');

      const firstHigh = result.find((m) => m.title === 'First High Score');
      expect(firstHigh).toBeDefined();
      expect(firstHigh?.date).toBe('2026-10-08');

      const excellence = result.find((m) => m.title === 'Excellence Attained');
      expect(excellence).toBeDefined();
      expect(excellence?.date).toBe('2026-10-12');

      const century = result.find((m) => m.title === 'Century Club');
      expect(century).toBeDefined();
      expect(century?.date).toBe('2026-10-08');
    });
  });

  describe('getMilestoneSummary', () => {
    it('aggregates total counts, auto vs custom, and categories', () => {
      const milestones: Milestone[] = [
        {
          id: -1,
          title: 'Journey Begun',
          description: 'Desc',
          date: '2026-10-01',
          isAutoGenerated: true,
          category: 'syllabus',
          createdAt: '2026-10-01T00:00:00.000Z',
        },
        {
          id: -2,
          title: 'Centurion',
          description: 'Desc',
          date: '2026-10-04',
          isAutoGenerated: true,
          category: 'question_count',
          createdAt: '2026-10-04T00:00:00.000Z',
        },
        {
          id: 1,
          title: 'Bought Guidebooks',
          description: 'Custom milestone',
          date: '2026-10-02',
          isAutoGenerated: false,
          category: 'custom',
          createdAt: '2026-10-02T00:00:00.000Z',
        },
      ];

      const summary = getMilestoneSummary(milestones);
      expect(summary.totalMilestones).toBe(3);
      expect(summary.autoGeneratedCount).toBe(2);
      expect(summary.customCount).toBe(1);
      expect(summary.byCategory.syllabus).toBe(1);
      expect(summary.byCategory.question_count).toBe(1);
      expect(summary.byCategory.custom).toBe(1);
      expect(summary.recentMilestones[0].title).toBe('Centurion'); // newest date (2026-10-04)
    });
  });

  describe('filterAndSortMilestones', () => {
    const milestones: Milestone[] = [
      {
        id: -1,
        title: 'Journey Begun',
        description: 'First preparation step',
        date: '2026-10-01',
        isAutoGenerated: true,
        category: 'syllabus',
        createdAt: '2026-10-01T00:00:00.000Z',
      },
      {
        id: -2,
        title: 'Weekly Warrior',
        description: '7-day study streak',
        date: '2026-10-07',
        isAutoGenerated: true,
        category: 'streak',
        createdAt: '2026-10-07T00:00:00.000Z',
      },
      {
        id: 10,
        title: 'Enrolled in Coaching',
        description: 'Signed up for DUET batch',
        date: '2026-10-05',
        isAutoGenerated: false,
        category: 'custom',
        createdAt: '2026-10-05T00:00:00.000Z',
      },
    ];

    it('filters by category', () => {
      const filtered = filterAndSortMilestones(milestones, { category: 'streak' });
      expect(filtered.length).toBe(1);
      expect(filtered[0].title).toBe('Weekly Warrior');
    });

    it('filters by source', () => {
      const autoOnly = filterAndSortMilestones(milestones, { source: 'auto' });
      expect(autoOnly.length).toBe(2);

      const customOnly = filterAndSortMilestones(milestones, { source: 'custom' });
      expect(customOnly.length).toBe(1);
      expect(customOnly[0].title).toBe('Enrolled in Coaching');
    });

    it('filters by search query', () => {
      const searchResult = filterAndSortMilestones(milestones, { searchQuery: 'warrior' });
      expect(searchResult.length).toBe(1);
      expect(searchResult[0].title).toBe('Weekly Warrior');

      const descResult = filterAndSortMilestones(milestones, { searchQuery: 'coaching' });
      expect(descResult.length).toBe(1);
      expect(descResult[0].title).toBe('Enrolled in Coaching');
    });

    it('sorts newest first and oldest first', () => {
      const newest = filterAndSortMilestones(milestones, { sortOrder: 'newest' });
      expect(newest[0].date).toBe('2026-10-07');
      expect(newest[2].date).toBe('2026-10-01');

      const oldest = filterAndSortMilestones(milestones, { sortOrder: 'oldest' });
      expect(oldest[0].date).toBe('2026-10-01');
      expect(oldest[2].date).toBe('2026-10-07');
    });
  });

  describe('createCustomMilestoneSchema', () => {
    it('validates a valid custom milestone input', () => {
      const valid = {
        title: 'Target Set: 120 Marks',
        description: 'Set initial goal for DUET merit position',
        date: '2026-10-15',
        category: 'custom',
      };
      expect(() => createCustomMilestoneSchema.parse(valid)).not.toThrow();
    });

    it('rejects short title or invalid date', () => {
      expect(() =>
        createCustomMilestoneSchema.parse({
          title: 'A',
          description: 'Valid description',
          date: '2026-10-15',
          category: 'custom',
        })
      ).toThrow();

      expect(() =>
        createCustomMilestoneSchema.parse({
          title: 'Valid Title',
          description: 'Valid description',
          date: '15/10/2026',
          category: 'custom',
        })
      ).toThrow();
    });
  });
});

