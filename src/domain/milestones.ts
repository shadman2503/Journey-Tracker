import { z } from 'zod';
import type {
  Milestone,
  MilestoneCategory,
  StudySession,
  MockTest,
  TopicProgress,
  SyllabusTopic,
  SubjectId,
} from './types';

export const ALL_MILESTONE_CATEGORIES: MilestoneCategory[] = [
  'syllabus',
  'streak',
  'mock',
  'question_count',
  'study_time',
  'custom',
];

export interface MilestoneSummary {
  totalMilestones: number;
  autoGeneratedCount: number;
  customCount: number;
  byCategory: Record<MilestoneCategory, number>;
  recentMilestones: Milestone[];
}

export interface MilestoneFilterOptions {
  category?: MilestoneCategory | 'all';
  source?: 'all' | 'auto' | 'custom';
  searchQuery?: string;
  sortOrder?: 'newest' | 'oldest';
}

export const createCustomMilestoneSchema = z.object({
  title: z
    .string()
    .trim()
    .min(2, 'Title must be at least 2 characters')
    .max(80, 'Title cannot exceed 80 characters'),
  description: z
    .string()
    .trim()
    .min(3, 'Description must be at least 3 characters')
    .max(300, 'Description cannot exceed 300 characters'),
  date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Date must be in YYYY-MM-DD format'),
  category: z.enum([
    'syllabus',
    'streak',
    'mock',
    'question_count',
    'study_time',
    'custom',
  ]),
});

export type CreateCustomMilestoneInput = z.infer<typeof createCustomMilestoneSchema>;

const SUBJECT_NAMES: Record<SubjectId, string> = {
  math: 'Mathematics',
  physics: 'Physics',
  chemistry: 'Chemistry',
  english: 'English',
  cse: 'Computer Science',
};

/**
 * Detects auto-generated milestones from study sessions, mock tests, and syllabus progress.
 * Returns a list of auto-generated Milestone objects with deterministic negative IDs.
 */
export function detectAutoMilestones(
  topics: SyllabusTopic[],
  progressMap: Record<string, TopicProgress>,
  sessions: StudySession[],
  mockTests: MockTest[]
): Milestone[] {
  const autoMilestones: Milestone[] = [];
  let nextNegativeId = -1;

  const pushMilestone = (
    title: string,
    description: string,
    date: string,
    category: MilestoneCategory,
    icon?: string
  ) => {
    // Prevent duplicate titles
    if (autoMilestones.some((m) => m.title === title)) return;

    autoMilestones.push({
      id: nextNegativeId--,
      title,
      description,
      date,
      isAutoGenerated: true,
      category,
      createdAt: new Date().toISOString(),
      icon,
    });
  };

  // Sort sessions chronologically (oldest first)
  const sortedSessions = [...sessions].sort((a, b) => {
    const diff = new Date(a.date).getTime() - new Date(b.date).getTime();
    if (diff !== 0) return diff;
    return new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime();
  });

  // Sort mock tests chronologically (oldest first)
  const sortedMockTests = [...mockTests].sort((a, b) => {
    const diff = new Date(a.date).getTime() - new Date(b.date).getTime();
    if (diff !== 0) return diff;
    return new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime();
  });

  // 1. Journey Begun (First activity ever recorded)
  const allDates: string[] = [];
  if (sortedSessions.length > 0) allDates.push(sortedSessions[0].date);
  if (sortedMockTests.length > 0) allDates.push(sortedMockTests[0].date);

  if (allDates.length > 0) {
    allDates.sort((a, b) => new Date(a).getTime() - new Date(b).getTime());
    const journeyStartDate = allDates[0];
    pushMilestone(
      'Journey Begun',
      'Recorded your first preparation activity for DUET 2027',
      journeyStartDate,
      'syllabus',
      'compass'
    );
  }

  // 2. Practice Question Count Milestones
  const questionThresholds = [
    { count: 50, title: 'Fifty Questions Down', desc: 'Solved 50 practice questions', icon: 'target' },
    { count: 100, title: 'Centurion', desc: 'Solved 100 practice questions', icon: 'target' },
    { count: 250, title: 'Quarter Millennium', desc: 'Solved 250 practice questions', icon: 'award' },
    { count: 500, title: 'Half Millennium', desc: 'Solved 500 practice questions', icon: 'award' },
    { count: 1000, title: 'Thousand Strong', desc: 'Solved 1,000 practice questions', icon: 'trophy' },
    { count: 2500, title: 'Practice Titan', desc: 'Solved 2,500 practice questions', icon: 'trophy' },
  ];

  let cumulativeQuestions = 0;
  for (const session of sortedSessions) {
    cumulativeQuestions += session.questionsSolved;
    for (const threshold of questionThresholds) {
      if (cumulativeQuestions >= threshold.count) {
        pushMilestone(
          threshold.title,
          threshold.desc,
          session.date,
          'question_count',
          threshold.icon
        );
      }
    }
  }

  // 3. Study Hours Milestones
  const durationThresholds = [
    { minutes: 600, title: '10 Hours Dedicated', desc: 'Logged 10 hours of focused preparation', icon: 'clock' },
    { minutes: 1500, title: '25 Hours Dedicated', desc: 'Logged 25 hours of focused preparation', icon: 'clock' },
    { minutes: 3000, title: '50 Hours Dedicated', desc: 'Logged 50 hours of focused preparation', icon: 'clock' },
    { minutes: 6000, title: 'Century of Hours', desc: 'Logged 100 hours of focused preparation', icon: 'trophy' },
  ];

  let cumulativeMinutes = 0;
  for (const session of sortedSessions) {
    cumulativeMinutes += session.durationMinutes;
    for (const threshold of durationThresholds) {
      if (cumulativeMinutes >= threshold.minutes) {
        pushMilestone(
          threshold.title,
          threshold.desc,
          session.date,
          'study_time',
          threshold.icon
        );
      }
    }
  }

  // 4. Consecutive Streak Milestones
  const streakThresholds = [
    { days: 3, title: 'Consistency Spark', desc: 'Achieved a 3-day continuous study streak', icon: 'flame' },
    { days: 7, title: 'Weekly Warrior', desc: 'Achieved a 7-day continuous study streak', icon: 'flame' },
    { days: 14, title: 'Fortnight Focused', desc: 'Achieved a 14-day continuous study streak', icon: 'flame' },
    { days: 30, title: 'Iron Dedication', desc: 'Achieved a 30-day continuous study streak', icon: 'flame' },
  ];

  // Collect unique session dates
  const uniqueSessionDates = Array.from(new Set(sortedSessions.map((s) => s.date))).sort(
    (a, b) => new Date(a).getTime() - new Date(b).getTime()
  );

  let currentStreakRun = 0;
  let previousDateTime: number | null = null;
  const ONE_DAY_MS = 24 * 60 * 60 * 1000;

  for (const dateStr of uniqueSessionDates) {
    const currentDateTime = new Date(dateStr).getTime();
    if (previousDateTime === null) {
      currentStreakRun = 1;
    } else {
      const diffDays = Math.round((currentDateTime - previousDateTime) / ONE_DAY_MS);
      if (diffDays === 1) {
        currentStreakRun += 1;
      } else {
        currentStreakRun = 1;
      }
    }
    previousDateTime = currentDateTime;

    for (const threshold of streakThresholds) {
      if (currentStreakRun >= threshold.days) {
        pushMilestone(
          threshold.title,
          threshold.desc,
          dateStr,
          'streak',
          threshold.icon
        );
      }
    }
  }

  // 5. Syllabus Progress & Mastery Milestones
  const strongTopics: TopicProgress[] = [];
  for (const p of Object.values(progressMap)) {
    if (p.status === 'strong') {
      strongTopics.push(p);
    }
  }

  if (strongTopics.length > 0) {
    // Sort strong topics by updatedAt ascending
    strongTopics.sort((a, b) => new Date(a.updatedAt).getTime() - new Date(b.updatedAt).getTime());
    const firstStrongDate = strongTopics[0].updatedAt.slice(0, 10);
    pushMilestone(
      'First Topic Mastered',
      "Achieved 'Strong' mastery on your first syllabus topic",
      firstStrongDate,
      'syllabus',
      'sparkles'
    );
  }

  if (topics.length > 0) {
    const totalTopicsCount = topics.length;
    const strongCount = strongTopics.length;

    // Running check for syllabus mastery percentages
    const syllabusPercentMilestones = [
      { ratio: 0.25, title: 'Quarter Syllabus Covered', desc: 'Mastered 25% of the DUET syllabus', icon: 'award' },
      { ratio: 0.50, title: 'Halfway Milestone', desc: 'Mastered 50% of the DUET syllabus', icon: 'award' },
      { ratio: 0.75, title: 'Three Quarters Mastery', desc: 'Mastered 75% of the DUET syllabus', icon: 'trophy' },
      { ratio: 1.00, title: 'Full Syllabus Champion', desc: 'Mastered 100% of the complete DUET syllabus', icon: 'trophy' },
    ];

    for (const milestone of syllabusPercentMilestones) {
      const requiredTopics = Math.ceil(milestone.ratio * totalTopicsCount);
      if (strongCount >= requiredTopics && requiredTopics > 0) {
        // Find the date of the topic that met this required count
        const achievementTopic = strongTopics[requiredTopics - 1];
        const date = achievementTopic ? achievementTopic.updatedAt.slice(0, 10) : new Date().toISOString().slice(0, 10);
        pushMilestone(
          milestone.title,
          milestone.desc,
          date,
          'syllabus',
          milestone.icon
        );
      }
    }

    // Subject Completion Milestones
    const subjectList: SubjectId[] = ['math', 'physics', 'chemistry', 'english', 'cse'];
    for (const subjectId of subjectList) {
      const subjectTopics = topics.filter((t) => t.subjectId === subjectId);
      if (subjectTopics.length > 0) {
        const allSubjectStrong = subjectTopics.every(
          (t) => progressMap[t.id]?.status === 'strong'
        );
        if (allSubjectStrong) {
          // Find the latest updatedAt among these subject topics
          const subjectStrongDates = subjectTopics
            .map((t) => progressMap[t.id]?.updatedAt)
            .filter(Boolean) as string[];
          subjectStrongDates.sort((a, b) => new Date(b).getTime() - new Date(a).getTime());
          const latestDate = subjectStrongDates[0]?.slice(0, 10) || new Date().toISOString().slice(0, 10);
          pushMilestone(
            `${SUBJECT_NAMES[subjectId]} Mastered`,
            `Mastered all topics in ${SUBJECT_NAMES[subjectId]}`,
            latestDate,
            'syllabus',
            'book-open'
          );
        }
      }
    }
  }

  // 6. Mock Test Milestones
  if (sortedMockTests.length > 0) {
    pushMilestone(
      'First Mock Trial',
      'Completed your first practice or full mock test',
      sortedMockTests[0].date,
      'mock',
      'file-check'
    );

    // First 70%+ accuracy
    const mock70 = sortedMockTests.find((m) => m.accuracy >= 70);
    if (mock70) {
      pushMilestone(
        'First High Score',
        'Scored 70%+ accuracy on a mock test',
        mock70.date,
        'mock',
        'award'
      );
    }

    // First 80%+ accuracy
    const mock80 = sortedMockTests.find((m) => m.accuracy >= 80);
    if (mock80) {
      pushMilestone(
        'Excellence Attained',
        'Scored 80%+ accuracy on a mock test',
        mock80.date,
        'mock',
        'sparkles'
      );
    }

    // First 100+ score
    const mock100Score = sortedMockTests.find((m) => m.score >= 100);
    if (mock100Score) {
      pushMilestone(
        'Century Club',
        'Scored 100+ marks on a mock test',
        mock100Score.date,
        'mock',
        'trophy'
      );
    }

    // Mock count volume
    if (sortedMockTests.length >= 5) {
      pushMilestone(
        'Mock Veteran',
        'Completed 5 mock tests',
        sortedMockTests[4].date,
        'mock',
        'award'
      );
    }

    if (sortedMockTests.length >= 10) {
      pushMilestone(
        'Mock Master',
        'Completed 10 mock tests',
        sortedMockTests[9].date,
        'mock',
        'trophy'
      );
    }
  }

  // Return sorted newest date first
  return autoMilestones.sort(
    (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime()
  );
}

/**
 * Aggregates a list of unified milestones into overall and categorical summary statistics.
 */
export function getMilestoneSummary(milestones: Milestone[]): MilestoneSummary {
  const byCategory: Record<MilestoneCategory, number> = {
    syllabus: 0,
    streak: 0,
    mock: 0,
    question_count: 0,
    study_time: 0,
    custom: 0,
  };

  let autoGeneratedCount = 0;
  let customCount = 0;

  for (const m of milestones) {
    if (m.isAutoGenerated) {
      autoGeneratedCount++;
    } else {
      customCount++;
    }

    if (byCategory[m.category] !== undefined) {
      byCategory[m.category]++;
    } else {
      byCategory.custom++;
    }
  }

  // Sort newest first for recent list
  const sorted = [...milestones].sort(
    (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime()
  );

  return {
    totalMilestones: milestones.length,
    autoGeneratedCount,
    customCount,
    byCategory,
    recentMilestones: sorted.slice(0, 3),
  };
}

/**
 * Filters and sorts milestones by category, origin source, keyword query, and date ordering.
 */
export function filterAndSortMilestones(
  milestones: Milestone[],
  options: MilestoneFilterOptions = {}
): Milestone[] {
  let result = [...milestones];

  // Filter category
  if (options.category && options.category !== 'all') {
    result = result.filter((m) => m.category === options.category);
  }

  // Filter source
  if (options.source && options.source !== 'all') {
    if (options.source === 'auto') {
      result = result.filter((m) => m.isAutoGenerated);
    } else if (options.source === 'custom') {
      result = result.filter((m) => !m.isAutoGenerated);
    }
  }

  // Filter search query
  if (options.searchQuery && options.searchQuery.trim().length > 0) {
    const q = options.searchQuery.trim().toLowerCase();
    result = result.filter(
      (m) =>
        m.title.toLowerCase().includes(q) ||
        m.description.toLowerCase().includes(q)
    );
  }

  // Sort order
  const sortOrder = options.sortOrder || 'newest';
  result.sort((a, b) => {
    const diff = new Date(b.date).getTime() - new Date(a.date).getTime();
    return sortOrder === 'newest' ? diff : -diff;
  });

  return result;
}

