import { describe, it, expect } from 'vitest';
import {
  buildTimelineItems,
  groupTimelineByMonth,
  calculateTimelineStats,
} from './timeline';
import type { Milestone } from './types';

describe('timeline domain logic', () => {
  const mockMilestones: Milestone[] = [
    {
      id: -1,
      title: 'Journey Begun',
      description: 'First preparation step',
      date: '2026-10-01',
      isAutoGenerated: true,
      category: 'syllabus',
      createdAt: '',
    },
    {
      id: -2,
      title: 'Centurion',
      description: 'Solved 100 practice questions',
      date: '2026-10-15',
      isAutoGenerated: true,
      category: 'question_count',
      createdAt: '',
    },
    {
      id: 1,
      title: 'Bought Guidebooks',
      description: 'Targeted DUET preparation books',
      date: '2026-11-05',
      isAutoGenerated: false,
      category: 'custom',
      createdAt: '',
    },
  ];

  const targetExamDate = '2027-06-25';

  describe('buildTimelineItems', () => {
    it('creates timeline items and appends destination exam node', () => {
      const items = buildTimelineItems(mockMilestones, targetExamDate);

      expect(items.length).toBe(4);
      // First is Journey Begun (oldest date: 2026-10-01)
      expect(items[0].title).toBe('Journey Begun');
      expect(items[0].type).toBe('journey_start');

      // Last item is DUET Admission Test destination node
      const destination = items[items.length - 1];
      expect(destination.type).toBe('exam_destination');
      expect(destination.title).toBe('DUET Admission Test');
      expect(destination.date).toBe(targetExamDate);
      expect(destination.category).toBe('destination');
    });

    it('sorts timeline items newest to oldest when requested', () => {
      const items = buildTimelineItems(mockMilestones, targetExamDate, {
        sortOrder: 'newest_to_oldest',
      });

      expect(items[0].title).toBe('DUET Admission Test');
      expect(items[items.length - 1].title).toBe('Journey Begun');
    });

    it('filters timeline items by category', () => {
      const questionItems = buildTimelineItems(mockMilestones, targetExamDate, {
        category: 'question_count',
      });

      expect(questionItems.length).toBe(1);
      expect(questionItems[0].title).toBe('Centurion');

      const destinationItems = buildTimelineItems(mockMilestones, targetExamDate, {
        category: 'destination',
      });

      expect(destinationItems.length).toBe(1);
      expect(destinationItems[0].title).toBe('DUET Admission Test');
    });

    it('filters timeline items by search query', () => {
      const searched = buildTimelineItems(mockMilestones, targetExamDate, {
        searchQuery: 'Guidebooks',
      });

      expect(searched.length).toBe(1);
      expect(searched[0].title).toBe('Bought Guidebooks');
    });
  });

  describe('groupTimelineByMonth', () => {
    it('groups timeline items by month and formats header label', () => {
      const items = buildTimelineItems(mockMilestones, targetExamDate);
      const groups = groupTimelineByMonth(items);

      // October 2026, November 2026, June 2027
      expect(groups.length).toBe(3);
      expect(groups[0].monthKey).toBe('2026-10');
      expect(groups[0].monthLabel).toBe('October 2026');
      expect(groups[0].items.length).toBe(2);

      expect(groups[1].monthKey).toBe('2026-11');
      expect(groups[1].monthLabel).toBe('November 2026');
      expect(groups[1].items.length).toBe(1);

      expect(groups[2].monthKey).toBe('2027-06');
      expect(groups[2].monthLabel).toBe('June 2027');
      expect(groups[2].items[0].title).toBe('DUET Admission Test');
    });
  });

  describe('calculateTimelineStats', () => {
    it('computes days elapsed, days remaining, and progress percentage', () => {
      const refDate = new Date('2026-10-31T00:00:00.000Z');
      const stats = calculateTimelineStats(mockMilestones, '2026-11-30', refDate);

      expect(stats.totalEvents).toBe(3);
      expect(stats.firstEventDate).toBe('2026-10-01');
      expect(stats.targetExamDate).toBe('2026-11-30');
      // 30 days between Oct 1 and Oct 31
      expect(stats.daysElapsed).toBe(30);
      // 30 days between Oct 31 and Nov 30
      expect(stats.daysRemaining).toBe(30);
      // 30 / 60 = 50%
      expect(stats.journeyProgressPercent).toBe(50);
    });

    it('handles empty milestones gracefully', () => {
      const stats = calculateTimelineStats([], '2027-06-25');
      expect(stats.totalEvents).toBe(0);
      expect(stats.firstEventDate).toBeNull();
      expect(stats.daysElapsed).toBe(0);
      expect(stats.daysRemaining).toBeGreaterThan(0);
    });
  });
});

