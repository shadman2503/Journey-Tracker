import type { Milestone, MilestoneCategory } from './types';

export type TimelineNodeType = 'milestone' | 'exam_destination' | 'journey_start';

export interface TimelineItem {
  id: string | number;
  type: TimelineNodeType;
  title: string;
  description: string;
  date: string;
  category: MilestoneCategory | 'destination';
  isAutoGenerated: boolean;
  isCompleted: boolean;
  icon?: string;
}

export interface TimelineMonthGroup {
  monthKey: string;
  monthLabel: string;
  year: number;
  items: TimelineItem[];
}

export interface TimelineStats {
  totalEvents: number;
  firstEventDate: string | null;
  targetExamDate: string;
  daysElapsed: number;
  daysRemaining: number;
  journeyProgressPercent: number;
}

export interface TimelineFilterOptions {
  category?: MilestoneCategory | 'destination' | 'all';
  sortOrder?: 'oldest_to_newest' | 'newest_to_oldest';
  searchQuery?: string;
}

const MONTH_NAMES = [
  'January',
  'February',
  'March',
  'April',
  'May',
  'June',
  'July',
  'August',
  'September',
  'October',
  'November',
  'December',
];

/**
 * Transforms unified milestones and target exam date into an ordered list of timeline items.
 */
export function buildTimelineItems(
  milestones: Milestone[],
  targetExamDate: string,
  options: TimelineFilterOptions = {}
): TimelineItem[] {
  const items: TimelineItem[] = [];

  // 1. Convert milestones to timeline items
  for (const m of milestones) {
    items.push({
      id: m.id ?? `milestone-${m.title}-${m.date}`,
      type: m.title === 'Journey Begun' ? 'journey_start' : 'milestone',
      title: m.title,
      description: m.description,
      date: m.date,
      category: m.category,
      isAutoGenerated: m.isAutoGenerated,
      isCompleted: true,
      icon: m.icon,
    });
  }

  // 2. Add the destination exam horizon node if target date is set
  if (targetExamDate) {
    const todayStr = new Date().toISOString().slice(0, 10);
    const isPastOrToday = targetExamDate <= todayStr;

    items.push({
      id: 'exam-target-destination',
      type: 'exam_destination',
      title: 'DUET Admission Test',
      description: 'The ultimate target destination of your preparation journey',
      date: targetExamDate,
      category: 'destination',
      isAutoGenerated: false,
      isCompleted: isPastOrToday,
      icon: 'star',
    });
  }

  let result = items;

  // Filter by category
  if (options.category && options.category !== 'all') {
    result = result.filter((item) => item.category === options.category);
  }

  // Filter by search query
  if (options.searchQuery && options.searchQuery.trim().length > 0) {
    const q = options.searchQuery.trim().toLowerCase();
    result = result.filter(
      (item) =>
        item.title.toLowerCase().includes(q) ||
        item.description.toLowerCase().includes(q)
    );
  }

  // Sort order (default oldest to newest: timeline advances into future)
  const sortOrder = options.sortOrder || 'oldest_to_newest';
  result.sort((a, b) => {
    const diff = new Date(a.date).getTime() - new Date(b.date).getTime();
    return sortOrder === 'oldest_to_newest' ? diff : -diff;
  });

  return result;
}

/**
 * Groups timeline items by Month-Year for visual sectioning on the timeline spine.
 */
export function groupTimelineByMonth(items: TimelineItem[]): TimelineMonthGroup[] {
  const groupsMap = new Map<string, TimelineItem[]>();

  for (const item of items) {
    const monthKey = item.date.slice(0, 7); // e.g. "2026-10"
    if (!groupsMap.has(monthKey)) {
      groupsMap.set(monthKey, []);
    }
    groupsMap.get(monthKey)!.push(item);
  }

  const groups: TimelineMonthGroup[] = [];
  for (const [monthKey, groupItems] of groupsMap.entries()) {
    const [yearStr, monthStr] = monthKey.split('-');
    const year = parseInt(yearStr, 10) || new Date().getFullYear();
    const monthIndex = parseInt(monthStr, 10) - 1;
    const monthName = MONTH_NAMES[monthIndex] || monthStr;
    const monthLabel = `${monthName} ${year}`;

    groups.push({
      monthKey,
      monthLabel,
      year,
      items: groupItems,
    });
  }

  return groups;
}

/**
 * Calculates preparation journey metrics: elapsed time, days remaining to exam, and traversed progress.
 */
export function calculateTimelineStats(
  milestones: Milestone[],
  targetExamDate: string,
  referenceDate: Date = new Date()
): TimelineStats {
  const ONE_DAY_MS = 24 * 60 * 60 * 1000;
  const refTime = referenceDate.getTime();
  const examTime = new Date(targetExamDate).getTime();

  // Find first event date
  let firstEventDate: string | null = null;
  if (milestones.length > 0) {
    const sortedDates = milestones
      .map((m) => m.date)
      .sort((a, b) => new Date(a).getTime() - new Date(b).getTime());
    firstEventDate = sortedDates[0];
  }

  const startTime = firstEventDate
    ? new Date(firstEventDate).getTime()
    : refTime;

  const daysElapsed = Math.max(0, Math.floor((refTime - startTime) / ONE_DAY_MS));
  const daysRemaining = Math.max(0, Math.ceil((examTime - refTime) / ONE_DAY_MS));
  const totalJourneyDays = Math.max(1, Math.floor((examTime - startTime) / ONE_DAY_MS));

  let journeyProgressPercent = Math.round((daysElapsed / totalJourneyDays) * 100);
  if (isNaN(journeyProgressPercent)) journeyProgressPercent = 0;
  journeyProgressPercent = Math.min(100, Math.max(0, journeyProgressPercent));

  return {
    totalEvents: milestones.length,
    firstEventDate,
    targetExamDate,
    daysElapsed,
    daysRemaining,
    journeyProgressPercent,
  };
}

