export type SubjectId = 'math' | 'physics' | 'chemistry' | 'english' | 'cse';

export interface SubjectMeta {
  id: SubjectId;
  name: string;
  nameBn?: string;
  iconName: string;
  description: string;
  totalTopics: number;
  totalChapters: number;
}

export type TopicStatus =
  | 'not_started'
  | 'learning'
  | 'practicing'
  | 'strong'
  | 'needs_revision';

export interface SyllabusTopic {
  id: string;
  subjectId: SubjectId;
  section: string;
  chapter: string;
  name: string;
  order: number;
}

export type Topic = SyllabusTopic;

export interface TopicProgress {
  topicId: string;
  status: TopicStatus;
  notes?: string;
  lastStudiedAt?: string;
  updatedAt: string;
}

export interface SubjectProgressSummary {
  subjectId: SubjectId;
  subjectName: string;
  totalTopics: number;
  completedTopics: number; // status === 'strong'
  inProgressTopics: number; // status === 'learning' || 'practicing'
  needsRevisionTopics: number; // status === 'needs_revision'
  notStartedTopics: number; // status === 'not_started' or untracked
  percentage: number; // 0 to 100 weighted
}

export interface OverallProgressSummary {
  totalTopics: number;
  completedTopics: number;
  inProgressTopics: number;
  needsRevisionTopics: number;
  notStartedTopics: number;
  percentage: number; // 0 to 100 weighted across all subjects
  subjects: Record<SubjectId, SubjectProgressSummary>;
}

export interface StudySession {
  id?: number;
  date: string;
  subjectId: SubjectId;
  topicId: string;
  durationMinutes: number;
  questionsSolved: number;
  correctAnswers: number;
  notes?: string;
  createdAt: string;
}

export type MistakeType =
  | 'conceptual'
  | 'calculation'
  | 'formula'
  | 'careless'
  | 'misreading'
  | 'time_management';

export type MistakeStatus = 'unresolved' | 'reviewing' | 'fixed';

export interface Mistake {
  id?: number;
  subjectId: SubjectId;
  topicId: string;
  questionRef: string;
  whatWentWrong: string;
  correctSolution: string;
  type: MistakeType;
  status: MistakeStatus;
  reviewDate?: string;
  createdAt: string;
}

export interface MockTest {
  id?: number;
  testName: string;
  date: string;
  subjectId?: SubjectId;
  totalQuestions: number;
  correctAnswers: number;
  wrongAnswers: number;
  score: number;
  accuracy: number;
  timeTakenMinutes: number;
  notes?: string;
  createdAt: string;
}

export type MilestoneCategory =
  | 'syllabus'
  | 'streak'
  | 'mock'
  | 'question_count'
  | 'study_time'
  | 'custom';

export interface Milestone {
  id?: number;
  title: string;
  description: string;
  date: string;
  isAutoGenerated: boolean;
  category: MilestoneCategory;
  createdAt: string;
  icon?: string;
}

