import { describe, it, expect, beforeEach, vi } from 'vitest';
import {
  getCurrentEntityCounts,
  exportBackupData,
  importBackupData,
  clearAllLocalData,
} from './backupService';
import { useCountdownStore } from '@/stores/useCountdownStore';

const {
  mockTopicProgress,
  mockStudySessions,
  mockMistakes,
  mockMockTests,
  mockMilestones,
} = vi.hoisted(() => ({
  mockTopicProgress: {
    count: vi.fn(),
    toArray: vi.fn(),
    clear: vi.fn(),
    bulkPut: vi.fn(),
  },
  mockStudySessions: {
    count: vi.fn(),
    toArray: vi.fn(),
    clear: vi.fn(),
    bulkAdd: vi.fn(),
  },
  mockMistakes: {
    count: vi.fn(),
    toArray: vi.fn(),
    clear: vi.fn(),
    bulkAdd: vi.fn(),
  },
  mockMockTests: {
    count: vi.fn(),
    toArray: vi.fn(),
    clear: vi.fn(),
    bulkAdd: vi.fn(),
  },
  mockMilestones: {
    count: vi.fn(),
    toArray: vi.fn(),
    clear: vi.fn(),
    bulkAdd: vi.fn(),
  },
}));

vi.mock('@/storage/dexie/db', () => ({
  db: {
    topicProgress: mockTopicProgress,
    studySessions: mockStudySessions,
    mistakes: mockMistakes,
    mockTests: mockMockTests,
    milestones: mockMilestones,
    transaction: vi.fn().mockImplementation(async (_mode, _tables, callback) => {
      return callback();
    }),
  },
}));

describe('backupService', () => {
  const samplePayload = {
    version: 1,
    appName: 'DUET 2027 Journey Tracker',
    exportedAt: '2026-10-12T10:00:00Z',
    data: {
      topicProgress: [
        {
          topicId: 'math-calc-01',
          status: 'strong',
          notes: 'Finished all calculus',
          updatedAt: '2026-10-10T12:00:00Z',
        },
      ],
      studySessions: [
        {
          id: 1,
          date: '2026-10-05',
          subjectId: 'math',
          topicId: 'math-calc-01',
          durationMinutes: 60,
          questionsSolved: 30,
          correctAnswers: 25,
          createdAt: '2026-10-05',
        },
      ],
      mistakes: [
        {
          id: 1,
          subjectId: 'math',
          topicId: 'math-calc-01',
          questionRef: 'Q1',
          whatWentWrong: 'Sign error',
          correctSolution: 'Check sign',
          type: 'calculation',
          status: 'fixed',
          createdAt: '2026-10-05',
        },
      ],
      mockTests: [
        {
          id: 1,
          testName: 'Test 1',
          date: '2026-10-08',
          totalQuestions: 100,
          correctAnswers: 70,
          wrongAnswers: 20,
          score: 65,
          accuracy: 70,
          timeTakenMinutes: 120,
          createdAt: '2026-10-08',
        },
      ],
      milestones: [
        {
          id: 1,
          title: 'Milestone 1',
          description: 'Desc',
          date: '2026-10-05',
          isAutoGenerated: true,
          category: 'syllabus',
          createdAt: '2026-10-05',
        },
      ],
      countdown: {
        targetDate: '2027-06-20T09:00:00+06:00',
        examTitle: 'DUET 2027 Admission Test',
      },
    },
    summary: {
      totalTopicsTracked: 1,
      totalSessions: 1,
      totalMistakes: 1,
      totalMockTests: 1,
      totalMilestones: 1,
    },
  };

  beforeEach(() => {
    vi.clearAllMocks();
  });

  describe('getCurrentEntityCounts', () => {
    it('returns counts from all 5 Dexie tables', async () => {
      mockTopicProgress.count.mockResolvedValue(10);
      mockStudySessions.count.mockResolvedValue(25);
      mockMistakes.count.mockResolvedValue(4);
      mockMockTests.count.mockResolvedValue(3);
      mockMilestones.count.mockResolvedValue(6);

      const counts = await getCurrentEntityCounts();
      expect(counts).toEqual({
        topicProgress: 10,
        studySessions: 25,
        mistakes: 4,
        mockTests: 3,
        milestones: 6,
      });
    });
  });

  describe('exportBackupData', () => {
    it('aggregates all tables and countdown into a valid JSON backup payload', async () => {
      mockTopicProgress.toArray.mockResolvedValue([{ topicId: 'math-01', status: 'strong', updatedAt: '' }]);
      mockStudySessions.toArray.mockResolvedValue([]);
      mockMistakes.toArray.mockResolvedValue([]);
      mockMockTests.toArray.mockResolvedValue([]);
      mockMilestones.toArray.mockResolvedValue([]);

      const result = await exportBackupData();
      expect(result.payload.version).toBe(1);
      expect(result.payload.appName).toBe('DUET 2027 Journey Tracker');
      expect(result.payload.data.topicProgress.length).toBe(1);
      expect(result.jsonString).toContain('DUET 2027 Journey Tracker');
      expect(result.filename).toMatch(/^duet-2027-journey-tracker-backup-\d{4}-\d{2}-\d{2}\.json$/);
    });
  });

  describe('importBackupData', () => {
    it('returns error if json payload is invalid', async () => {
      const invalidJson = '{"version": 1}';
      const result = await importBackupData(invalidJson, 'overwrite');
      expect(result.success).toBe(false);
      expect(result.error).toBeDefined();
    });

    it('clears all tables and restores records in overwrite mode', async () => {
      const jsonStr = JSON.stringify(samplePayload);
      const result = await importBackupData(jsonStr, 'overwrite');

      expect(result.success).toBe(true);
      expect(result.mode).toBe('overwrite');
      expect(result.restoredCounts.topicProgress).toBe(1);
      expect(result.restoredCounts.studySessions).toBe(1);

      // Verify clear called on all tables
      expect(mockTopicProgress.clear).toHaveBeenCalled();
      expect(mockStudySessions.clear).toHaveBeenCalled();
      expect(mockMistakes.clear).toHaveBeenCalled();
      expect(mockMockTests.clear).toHaveBeenCalled();
      expect(mockMilestones.clear).toHaveBeenCalled();

      // Verify bulkPut and bulkAdd called
      expect(mockTopicProgress.bulkPut).toHaveBeenCalledWith(samplePayload.data.topicProgress);
      expect(mockStudySessions.bulkAdd).toHaveBeenCalledWith(samplePayload.data.studySessions);
      expect(mockMistakes.bulkAdd).toHaveBeenCalledWith(samplePayload.data.mistakes);
      expect(mockMockTests.bulkAdd).toHaveBeenCalledWith(samplePayload.data.mockTests);
      expect(mockMilestones.bulkAdd).toHaveBeenCalledWith(samplePayload.data.milestones);
    });

    it('preserves existing data and strips auto IDs to avoid collision in merge mode', async () => {
      const jsonStr = JSON.stringify(samplePayload);
      const result = await importBackupData(jsonStr, 'merge');

      expect(result.success).toBe(true);
      expect(result.mode).toBe('merge');

      // In merge mode, clear must NOT be called!
      expect(mockTopicProgress.clear).not.toHaveBeenCalled();
      expect(mockStudySessions.clear).not.toHaveBeenCalled();
      expect(mockMistakes.clear).not.toHaveBeenCalled();

      // In merge mode, studySessions added without explicit ID
      expect(mockStudySessions.bulkAdd).toHaveBeenCalledWith([
        expect.not.objectContaining({ id: 1 }),
      ]);
    });
  });

  describe('clearAllLocalData', () => {
    it('clears all 5 tables and resets countdown to default', async () => {
      const resetSpy = vi.spyOn(useCountdownStore.getState(), 'resetToDefault');

      await clearAllLocalData();

      expect(mockTopicProgress.clear).toHaveBeenCalled();
      expect(mockStudySessions.clear).toHaveBeenCalled();
      expect(mockMistakes.clear).toHaveBeenCalled();
      expect(mockMockTests.clear).toHaveBeenCalled();
      expect(mockMilestones.clear).toHaveBeenCalled();
      expect(resetSpy).toHaveBeenCalled();
    });
  });
});
