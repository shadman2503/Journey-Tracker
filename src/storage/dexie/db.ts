import Dexie, { type Table } from 'dexie';
import type { TopicProgress, StudySession, Mistake, MockTest, Milestone } from '@/domain/types';

export class JourneyTrackerDatabase extends Dexie {
  topicProgress!: Table<TopicProgress, string>;
  studySessions!: Table<StudySession, number>;
  mistakes!: Table<Mistake, number>;
  mockTests!: Table<MockTest, number>;
  milestones!: Table<Milestone, number>;

  constructor() {
    super('DUETJourneyTrackerDB');
    this.version(1).stores({
      topicProgress: 'topicId, status, updatedAt',
      studySessions: '++id, date, subjectId, topicId, createdAt',
      mistakes: '++id, subjectId, topicId, type, status, createdAt',
      mockTests: '++id, date, subjectId, createdAt',
      milestones: '++id, date, category, isAutoGenerated, createdAt',
    });
  }
}

export const db = new JourneyTrackerDatabase();

