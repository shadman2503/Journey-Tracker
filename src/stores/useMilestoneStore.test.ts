import { describe, it, expect, beforeEach, vi } from 'vitest';
import { useMilestoneStore } from './useMilestoneStore';
import type { Milestone } from '@/domain/types';

vi.mock('@/repositories/dexie', () => ({
  milestoneRepo: {
    getAll: vi.fn(),
    add: vi.fn(),
    delete: vi.fn(),
  },
}));

import { milestoneRepo } from '@/repositories/dexie';

describe('useMilestoneStore', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    useMilestoneStore.setState({
      customMilestones: [],
      loaded: false,
      isLoading: false,
      isAddModalOpen: false,
    });
  });

  it('loads custom milestones from repository and sorts them descending by date', async () => {
    const mockData: Milestone[] = [
      {
        id: 1,
        title: 'Bought Guidebooks',
        description: 'DUET previous years guides',
        date: '2026-10-01',
        isAutoGenerated: false,
        category: 'custom',
        createdAt: '2026-10-01T00:00:00.000Z',
      },
      {
        id: 2,
        title: 'Joined Coaching Batch',
        description: 'Morning weekend batch',
        date: '2026-10-06',
        isAutoGenerated: false,
        category: 'custom',
        createdAt: '2026-10-06T00:00:00.000Z',
      },
    ];

    vi.mocked(milestoneRepo.getAll).mockResolvedValue([...mockData]);

    await useMilestoneStore.getState().loadCustomMilestones();

    const state = useMilestoneStore.getState();
    expect(state.loaded).toBe(true);
    expect(state.isLoading).toBe(false);
    expect(state.customMilestones.length).toBe(2);
    // Newest date first
    expect(state.customMilestones[0].id).toBe(2);
    expect(state.customMilestones[1].id).toBe(1);
  });

  it('adds a new custom milestone, saves to repo, and prepends to store', async () => {
    vi.mocked(milestoneRepo.add).mockResolvedValue(99);

    const input = {
      title: 'Target: DUET Top 100',
      description: 'Determined to secure merit position',
      date: '2026-10-10',
      category: 'custom' as const,
    };

    const newId = await useMilestoneStore.getState().addCustomMilestone(input);

    expect(newId).toBe(99);
    expect(milestoneRepo.add).toHaveBeenCalledTimes(1);

    const state = useMilestoneStore.getState();
    expect(state.customMilestones.length).toBe(1);
    expect(state.customMilestones[0].id).toBe(99);
    expect(state.customMilestones[0].title).toBe('Target: DUET Top 100');
    expect(state.isAddModalOpen).toBe(false);
  });

  it('deletes a custom milestone and removes it from store', async () => {
    useMilestoneStore.setState({
      customMilestones: [
        {
          id: 5,
          title: 'To Delete',
          description: 'Desc',
          date: '2026-10-01',
          isAutoGenerated: false,
          category: 'custom',
          createdAt: '',
        },
      ],
      loaded: true,
    });

    vi.mocked(milestoneRepo.delete).mockResolvedValue(undefined);

    await useMilestoneStore.getState().deleteCustomMilestone(5);

    expect(milestoneRepo.delete).toHaveBeenCalledWith(5);
    expect(useMilestoneStore.getState().customMilestones.length).toBe(0);
  });

  it('unifies custom milestones with auto-generated milestones', () => {
    useMilestoneStore.setState({
      customMilestones: [
        {
          id: 1,
          title: 'Manual Goal',
          description: 'Custom',
          date: '2026-10-05',
          isAutoGenerated: false,
          category: 'custom',
          createdAt: '',
        },
      ],
    });

    const sessions = [
      {
        id: 1,
        date: '2026-10-01',
        subjectId: 'math' as const,
        topicId: 'math-01',
        durationMinutes: 30,
        questionsSolved: 20,
        correctAnswers: 18,
        wrongAnswers: 2,
        accuracy: 90,
        createdAt: '2026-10-01T00:00:00.000Z',
      },
    ];

    const unified = useMilestoneStore.getState().getUnifiedMilestones([], {}, sessions, []);
    expect(unified.length).toBe(2);
    // 2026-10-05 first, then 2026-10-01
    expect(unified[0].title).toBe('Manual Goal');
    expect(unified[1].title).toBe('Journey Begun');
  });

  it('controls add modal open/close states', () => {
    expect(useMilestoneStore.getState().isAddModalOpen).toBe(false);

    useMilestoneStore.getState().openAddModal();
    expect(useMilestoneStore.getState().isAddModalOpen).toBe(true);

    useMilestoneStore.getState().closeAddModal();
    expect(useMilestoneStore.getState().isAddModalOpen).toBe(false);
  });
});

