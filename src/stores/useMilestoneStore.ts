import { create } from 'zustand';
import type {
  Milestone,
  SyllabusTopic,
  TopicProgress,
  StudySession,
  MockTest,
} from '@/domain/types';
import { milestoneRepo } from '@/repositories/dexie';
import {
  createCustomMilestoneSchema,
  type CreateCustomMilestoneInput,
  detectAutoMilestones,
  getMilestoneSummary,
  type MilestoneSummary,
} from '@/domain/milestones';

interface MilestoneState {
  customMilestones: Milestone[];
  loaded: boolean;
  isLoading: boolean;
  isAddModalOpen: boolean;

  openAddModal: () => void;
  closeAddModal: () => void;
  loadCustomMilestones: () => Promise<void>;
  addCustomMilestone: (input: CreateCustomMilestoneInput) => Promise<number>;
  deleteCustomMilestone: (id: number) => Promise<void>;
  getUnifiedMilestones: (
    topics: SyllabusTopic[],
    progressMap: Record<string, TopicProgress>,
    sessions: StudySession[],
    mockTests: MockTest[]
  ) => Milestone[];
  getSummary: (
    topics: SyllabusTopic[],
    progressMap: Record<string, TopicProgress>,
    sessions: StudySession[],
    mockTests: MockTest[]
  ) => MilestoneSummary;
}

export const useMilestoneStore = create<MilestoneState>((set, get) => ({
  customMilestones: [],
  loaded: false,
  isLoading: false,
  isAddModalOpen: false,

  openAddModal: () => set({ isAddModalOpen: true }),
  closeAddModal: () => set({ isAddModalOpen: false }),

  loadCustomMilestones: async () => {
    if (get().loaded || get().isLoading) return;
    set({ isLoading: true });
    try {
      const records = await milestoneRepo.getAll();
      // Keep only custom milestones in this store collection if any
      const customOnly = records.filter((m) => !m.isAutoGenerated);
      customOnly.sort(
        (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime()
      );
      set({ customMilestones: customOnly, loaded: true, isLoading: false });
    } catch (err) {
      console.error('Failed to load custom milestones from Dexie:', err);
      set({ isLoading: false });
    }
  },

  addCustomMilestone: async (input: CreateCustomMilestoneInput) => {
    const validated = createCustomMilestoneSchema.parse(input);
    const now = new Date().toISOString();

    const newMilestoneData: Omit<Milestone, 'id'> = {
      title: validated.title,
      description: validated.description,
      date: validated.date,
      category: validated.category,
      isAutoGenerated: false,
      createdAt: now,
      icon: 'flag',
    };

    const id = await milestoneRepo.add(newMilestoneData);
    const created: Milestone = {
      ...newMilestoneData,
      id,
    };

    set((state) => ({
      customMilestones: [created, ...state.customMilestones].sort(
        (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime()
      ),
      isAddModalOpen: false,
    }));

    return id;
  },

  deleteCustomMilestone: async (id: number) => {
    await milestoneRepo.delete(id);
    set((state) => ({
      customMilestones: state.customMilestones.filter((m) => m.id !== id),
    }));
  },

  getUnifiedMilestones: (
    topics: SyllabusTopic[],
    progressMap: Record<string, TopicProgress>,
    sessions: StudySession[],
    mockTests: MockTest[]
  ) => {
    const autoMilestones = detectAutoMilestones(
      topics,
      progressMap,
      sessions,
      mockTests
    );
    const unified = [...get().customMilestones, ...autoMilestones];
    return unified.sort(
      (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime()
    );
  },

  getSummary: (
    topics: SyllabusTopic[],
    progressMap: Record<string, TopicProgress>,
    sessions: StudySession[],
    mockTests: MockTest[]
  ) => {
    const unified = get().getUnifiedMilestones(
      topics,
      progressMap,
      sessions,
      mockTests
    );
    return getMilestoneSummary(unified);
  },
}));

